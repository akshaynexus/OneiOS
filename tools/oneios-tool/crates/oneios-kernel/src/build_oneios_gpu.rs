//! `oneios-tool kernel gen gpu` (was kernel/patches/oneios-hosted/gpu/build-oneios-gpu.py).
//!
//! The hosted kernel's GPU archive, built between the two kernel passes from the compile records of the first:
//!
//!   build/oneios-gpu/liboneiosgpu.a    OneiOSGpu.cpp (the patch folder: oneios_gpu3d_start) and Droid-VM's virtio-gpu 3D
//!                                      kernel driver, unchanged: UniXNU-droidvm package/DroidVMVirtioGpu.cpp and
//!                                      DroidVMVirtioGpu3D.cpp, with NativeAdreno's DroidVMVirtgpuABI.h
//!
//! Force-loaded by CONFIG_XNU_EXTRA_LD_ARCHIVES and started from oneios_board_late_start (0005-gpu-3d.patch).
//! kernel/build-hosted.sh adds it to the board's archives of the build's device repository; the VM kernel
//! (build-linux.sh) does not build it.
//!
//! Metal's kernel side is in the same archive: the NativeAdreno pieces Droid-VM builds beside the driver (the user
//! client AGXDeviceUserClient and the IOKit surface, execbuf, memory, the PM4 encoder, and package/DroidVMGpu.cpp which
//! publishes them), built in build/oneios-gpu/adreno/ by Droid-VM's own ipados27/scripts/build-droidvm-gpu.py run up to
//! its accelerator step (so with its edits to NativeAdrenoPublish.cpp and NativeAdrenoMemory.cpp), and then what that
//! step does, for this kernel collection:
//!
//!   NativeAdrenoAccelerator.late.o   NativeAdreno's staged AGXAccelerator, a subclass of the collection's
//!                                    IOAcceleratorES (com.apple.iokit.IOGPUFamily); its static initializer is taken
//!                                    out of __mod_init_func and made global, DroidVMGpu.cpp runs it after the family
//!                                    has loaded
//!   IOAcceleratorES-bindings.o       stubs for the parent's protected constructor and base destructor
//!   IOAcceleratorES-originals.o        `bti c; b <name>.original`, <name>.original absolute at the function's address
//!                                      in the collection: XnuPrelink's emitter retargets the branch (as ../aes does;
//!                                      Droid-VM's literal `ldr x16; br x16` is wrong under xnuhost's slide); and the
//!                                      parent's metaclass as an absolute symbol, with its link address and size as
//!                                      numbers for OneiOSAdreno.cpp's check and slide
//!   OneiOSAdreno.o                   the patch folder: the start, the bound-parent check, the superclass slide, the self-test
//!
//! The parent's addresses are IOAcceleratorES-24A446-v54.json in the patch folder (kernel/prelink/classes.py's record
//! of the class in the iPhone18,2 kernelcache; addresses only). The class must have the shape NativeMetal's
//! OriginalAcceleratorABI.h declares, which is the iPad's (Droid-VM's scripts/data/ioaccelerator-base-abi-24A446.json):
//! 136 bytes, IOService's 168 slots, only 0, 1 (destructors) and 7 (getMetaClass) its own; the protected constructor
//! 0x78 before the complete destructor and the base destructor 8 before it (read from the code: both constructors call
//! IOService's with the caller's metaclass and store the vtable; the base destructor is `bti c; b IOService::~IOService`).
//! DroidVMGpu.cpp is compiled from a staged copy with the changes of staged/gpu.rs: the start condition is
//! OneiOSAdreno.cpp's, the publish runs on the caller's thread, the bound parent is checked, and the superclass link is
//! slid before postModLoad.
//!
//! ONEIOS_GPU_ADRENO=0 in the environment leaves all of this out of the archive (compiled only, as a check);
//! adreno/status.json says what was compiled and linked.
//!
//! Run by UniXNU's driver in the build tree, with UNIXNU_DEVICE = the device repository. No Apple file is read.
//! The generated files say "Generated by build-oneios-gpu.py": the script this module replaced (kept so that the
//! files stay the ones the script wrote).

use crate::class_record::{pylist, ClassRecord};
use crate::drivers_build::Record;
use crate::gen::{self, fail, Compile, Ctx};
use crate::staged::gpu::GPU;
use anyhow::{Context, Result};
use oneios_common::pyjson::Value;
use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

const REQUIRED: [&str; 4] = ["_oneios_gpu3d_start", "_droidvm_virtgpu_call", "_droidvm_virtgpu_close", "__ZN16DroidVMVirtioGpu5startEv"];
const REQUIRED_ADRENO: [&str; 12] = ["_oneios_adreno_start", "_sheng_gpu_power_probe", "_native_adreno_publish", "_native_adreno_new_user_client",
                                     "_native_adreno_accelerator_allocate", "__GLOBAL__sub_I_NativeAdrenoAccelerator.cpp", "_droidvm_gpu_window_base",
                                     "_AdrenoPM4Type7", "__ZN15IOAcceleratorESC2EPK11OSMetaClass", "__ZN15IOAcceleratorESD2Ev",
                                     "_oneios_adreno_parent_meta_link", "__ZN14AGXAccelerator10gMetaClassE"];
const CLASS: &str = "IOAcceleratorES";
const META: &str = "__ZN15IOAcceleratorES10gMetaClassE";
/// Where Droid-VM's build-droidvm-gpu.py is cut: the line that starts its accelerator step.
const CUT: &str = "print(subprocess.run(['python3', ROOT / 'scripts/build-adreno740-accelerator.py']";

struct Places {
    here: PathBuf,
    package: PathBuf,
    adreno: PathBuf,
    classes: PathBuf,
    accelerator_abi: PathBuf,
}

/// The assembly of the parent's bindings, from the class reader's record of this kernelcache, and the names bound.
pub fn bindings(classes: &Path) -> Result<(String, String, BTreeSet<String>)> {
    let script = "build-oneios-gpu";
    let record = ClassRecord::load(classes, CLASS, script)?;
    if !record.is_shape("com.apple.iokit.IOGPUFamily", 136, 168)? {
        fail!("{script}: {CLASS} is not the class OriginalAcceleratorABI.h describes (136 bytes, 168 slots, IOGPUFamily)");
    }
    let own = record.own_slots()?;
    if !own.iter().copied().eq([0, 1, 7]) {
        fail!("{script}: {CLASS} has slots of its own besides the destructors and getMetaClass ({}): it is not a plain IOService", pylist(&own));
    }
    record.check_structors(script, CLASS)?;
    let functions = [("__ZN15IOAcceleratorESC2EPK11OSMetaClass".to_string(), record.constructor(script, CLASS)?),
                     ("__ZN15IOAcceleratorESD2Ev".to_string(), record.base_destructor()?)];
    let (stubs, targets) = record.bindings("build-oneios-gpu.py", META, "_oneios_adreno", &functions);
    let bound = functions.iter().map(|(name, _)| name.clone()).chain([META.to_string()]).collect();
    Ok((stubs, targets, bound))
}

/// NativeAdreno's staged AGXAccelerator against the collection's IOAcceleratorES, and OneiOSAdreno.cpp.
fn accelerator(ctx: &Ctx, places: &Places, out: &Path, record: &Record) -> Result<Vec<PathBuf>> {
    let stage = out.join("accelerator");
    let _ = std::fs::remove_dir_all(&stage);
    gen::mkdirs(&stage.join("Adreno740"))?;
    std::fs::create_dir(stage.join("AdrenoMetal")).context("accelerator/AdrenoMetal")?;
    // The source includes "../AdrenoMetal/OriginalAcceleratorABI.h": NativeMetal's header, beside the driver as in UniXNU's tree.
    copyfile(&places.accelerator_abi, &stage.join("AdrenoMetal/OriginalAcceleratorABI.h"))?;
    let source = stage.join("Adreno740/NativeAdrenoAccelerator.cpp"); // the same file name: the static initializer is named after it
    copyfile(&places.adreno.join("NativeAdrenoAccelerator.cpp"), &source)?;
    let compile = Compile { ctx, shown: 6000 };
    let include = ["-I".to_string(), gen::s(&places.adreno), "-I".to_string(), gen::s(&ctx.tree.join(".cache/xnu-work/osfmk"))];
    let mut objects = Vec::new();
    for (path, extra) in [(source, vec!["-Wno-overloaded-virtual".to_string()]), (places.here.join("OneiOSAdreno.cpp"), vec![])] {
        let object = stage.join(gen::stem(&path) + ".o");
        let arguments: Vec<String> = extra.into_iter().chain(include.iter().cloned()).collect();
        objects.push(compile.object(record, &path, &object, &arguments)?);
    }
    let (stubs, targets, bound) = bindings(&places.classes)?;
    let undefined: BTreeSet<String> = gen::output(&[gen::which("llvm-nm", "nm"), "-u".into(), gen::s(&objects[0])])?.lines()
        .filter(|line| line.contains("IOAcceleratorES")).filter_map(|line| line.split_whitespace().last().map(str::to_string)).collect();
    if undefined.difference(&bound).next().is_some() || undefined.intersection(&bound).next().is_none() {
        let unbound: Vec<String> = undefined.difference(&bound).map(|name| format!("'{name}'")).collect();
        fail!("build-oneios-gpu: NativeAdrenoAccelerator.cpp imports {} of the original base, which are not bound", pylist(unbound));
    }
    // The static initializer registers the class: it runs when DroidVMGpu.cpp calls it, after IOGPUFamily has loaded.
    let late = stage.join("NativeAdrenoAccelerator.late.o");
    gen::late_object(&gen::which("llvm-objcopy", "objcopy"), &objects[0], &late, &["__DATA,__mod_init_func"],
                     "__GLOBAL__sub_I_NativeAdrenoAccelerator.cpp")?;
    objects[0] = late;
    objects.extend(gen::assemble(record, &stage, &[("IOAcceleratorES-bindings", &stubs), ("IOAcceleratorES-originals", &targets)])?);
    Ok(objects)
}

/// `shutil.copyfile`.
fn copyfile(from: &Path, to: &Path) -> Result<()> {
    std::fs::write(to, gen::read_bytes(from)?).with_context(|| format!("{}", to.display()))
}

fn not_compiled(why: String) -> Value {
    let mut status = Value::dict();
    status.set("compiled", false);
    status.set("why", why);
    status
}

/// `target.exists()` and, for a folder, something in it.
fn checked_out(target: &Path) -> bool {
    target.exists() && !(target.is_dir() && std::fs::read_dir(target).map(|mut entries| entries.next().is_none()).unwrap_or(true))
}

/// DroidVMGpu.cpp with the changes of staged/gpu.rs; Err is the anchor that is not there exactly once.
pub fn staged_text(text: String) -> std::result::Result<String, String> {
    let mut text = text;
    for (anchor, replacement) in GPU {
        if text.matches(anchor).count() != 1 {
            return Err(format!("DroidVMGpu.cpp no longer has exactly one {}", anchor.trim()));
        }
        text = text.replace(anchor, replacement);
    }
    Ok(text)
}

/// Droid-VM's build of the NativeAdreno face, up to (not including) its accelerator step.
fn adreno_build(ctx: &Ctx, places: &Places, out: &Path) -> Result<Value> {
    let script = ctx.repo.join("external/UniXNU-droidvm/ipados27/scripts/build-droidvm-gpu.py");
    let text = gen::read_text(&script)?;
    if text.matches(CUT).count() != 1 {
        return Ok(not_compiled("build-droidvm-gpu.py no longer calls the accelerator build where expected".into()));
    }
    // Its layout: ROOT/drivers/Adreno740, ROOT/kits/{ArmSmmu4K,AdrenoPM4,droidvm}, ROOT/.cache/xnu-work, ROOT/build/xnu.
    let root = out.join("root");
    let _ = std::fs::remove_dir_all(&root);
    for folder in ["drivers", "kits/droidvm", ".cache", "build", "scripts"] {
        gen::mkdirs(&root.join(folder))?;
    }
    let links = [("drivers/Adreno740", places.adreno.clone()), ("kits/ArmSmmu4K", ctx.repo.join("external/ArmSmmu4K")),
                 ("kits/AdrenoPM4", ctx.repo.join("external/AdrenoPM4")), (".cache/xnu-work", ctx.tree.join(".cache/xnu-work")),
                 ("build/xnu", ctx.tree.join("build/xnu"))];
    for (name, target) in links {
        if !checked_out(&target) {
            return Ok(not_compiled(format!("{} is not checked out (scripts/setup/get-references.sh)", target.display())));
        }
        symlink(&gen::resolve(&target), &root.join(name))?;
    }
    // kits/droidvm: the package's files, with DroidVMGpu.cpp from a staged copy (staged/gpu.rs).
    let gpu = match staged_text(gen::read_text(&places.package.join("DroidVMGpu.cpp"))?) {
        Ok(gpu) => gpu,
        Err(why) => return Ok(not_compiled(why)),
    };
    for entry in std::fs::read_dir(&places.package).with_context(|| format!("{}", places.package.display()))? {
        let path = entry?.path();
        let staged = root.join("kits/droidvm").join(gen::name(&path));
        if gen::name(&path) == "DroidVMGpu.cpp" {
            gen::write_text(&staged, &gpu)?;
        } else {
            symlink(&gen::resolve(&path), &staged)?;
        }
    }
    let staged = root.join("scripts/build-droidvm-gpu.py");
    gen::write_text(&staged, &text[..text.find(CUT).expect("counted above")])?;
    // Droid-VM's own script (Python, not this repository's): run as it is.
    let result = gen::capture(&["python3".into(), "-I".into(), gen::s(&staged)], None, Some(1800))?;
    let mut objects = Value::list();
    if result.code == 0 {
        let mut found: Vec<String> = std::fs::read_dir(root.join("build/droidvm-gpu")).context("build/droidvm-gpu")?
            .filter_map(|entry| entry.ok().map(|e| e.path())).filter(|path| path.extension().is_some_and(|e| e == "o"))
            .filter_map(|path| path.strip_prefix(out).ok().map(gen::s)).collect();
        found.sort();
        found.into_iter().for_each(|name| objects.push(name));
    }
    let mut status = Value::dict();
    status.set("compiled", result.code == 0);
    status.set("objects", objects);
    status.set("linked", false);
    if result.code != 0 {
        let said = if result.stderr.is_empty() { &result.stdout } else { &result.stderr };
        status.set("why", gen::tail(said.trim(), 2000));
    }
    Ok(status)
}

fn symlink(target: &Path, link: &Path) -> Result<()> {
    std::os::unix::fs::symlink(target, link).with_context(|| format!("{}", link.display()))
}

pub fn main() -> Result<()> {
    let ctx = Ctx::new("build-oneios-gpu", "run through the kernel build")?;
    let here = ctx.repo.join("kernel/patches/oneios-hosted/gpu");
    let places = Places { package: ctx.repo.join("external/UniXNU-droidvm/package"), adreno: ctx.repo.join("external/NativeAdreno"),
                          classes: here.join("IOAcceleratorES-24A446-v54.json"), // kernel/prelink/classes.py's record of the class
                          accelerator_abi: ctx.repo.join("external/NativeMetal/OriginalAcceleratorABI.h"), here };
    let sources = [places.here.join("OneiOSGpu.cpp"), places.package.join("DroidVMVirtioGpu.cpp"), places.package.join("DroidVMVirtioGpu3D.cpp")];
    let mut needed = vec![ctx.repo.join("drivers/build.py"), places.adreno.join("DroidVMVirtgpuABI.h"),
                          ctx.records.join("iokit/DEVELOPMENT/IOPlatformExpert.cpo.json")];
    needed.extend(sources.iter().cloned());
    needed.extend([places.here.join("OneiOSAdreno.cpp"), places.classes.clone()]);
    gen::need_files(&needed, |path| format!("build-oneios-gpu: {} missing (scripts/setup/get-references.sh UniXNU-droidvm NativeAdreno)", path.display()))?;
    let out = ctx.tree.join("build/oneios-gpu");
    gen::mkdirs(&out)?;
    let record = ctx.record("iokit")?;
    // Metal's kernel side first: whether it is linked decides how OneiOSGpu.cpp is compiled.
    let link = std::env::var("ONEIOS_GPU_ADRENO").unwrap_or_else(|_| "1".into()) != "0";
    let adreno = out.join("adreno");
    gen::mkdirs(&adreno)?;
    let mut status = if link || std::env::var("ONEIOS_GPU_ADRENO_CHECK").unwrap_or_else(|_| "1".into()) != "0" {
        adreno_build(&ctx, &places, &adreno)?
    } else {
        not_compiled("skipped".into())
    };
    let compiled = status.get("compiled").and_then(Value::as_bool).unwrap_or(false);
    let why = status.get("why").and_then(Value::as_str).map(str::to_string);
    let mut linked = Vec::new();
    if link {
        if !compiled {
            eprintln!("{}", why.clone().unwrap_or_default());
            fail!("build-oneios-gpu: the NativeAdreno pieces did not build (ONEIOS_GPU_ADRENO=0 builds the archive without them)");
        }
        if !places.accelerator_abi.is_file() {
            fail!("build-oneios-gpu: {} missing (scripts/setup/get-references.sh NativeMetal)", places.accelerator_abi.display());
        }
        linked = gen::key_list(&status, "objects")?.iter().filter_map(Value::as_str).map(|name| adreno.join(name)).collect();
        linked.extend(accelerator(&ctx, &places, &adreno, &record)?);
        status.set("linked", true);
        let mut names: Vec<String> = linked.iter().filter_map(|p| p.strip_prefix(&adreno).ok().map(gen::s)).collect();
        names.sort();
        let mut list = Value::list();
        names.into_iter().for_each(|name| list.push(name));
        status.set("objects", list);
    }
    gen::write_json(&adreno.join("status.json"), &status, 2)?;
    let compile = Compile { ctx: &ctx, shown: 6000 };
    // DYNAMIC: the transport's queues and command buffers (about 9 MB) are allocated at start, not kernel bss: with
    // them in __DATA the kernel no longer fits the collection's stock layout (kernel/prelink, the board's Q7).
    let extra = ["-I".to_string(), gen::s(&places.package), "-I".to_string(), gen::s(&places.adreno), "-DDROIDVM_VIRTIO_GPU_DYNAMIC=1".to_string(),
                 format!("-DONEIOS_GPU_ADRENO={}", link as u8)];
    let mut objects = Vec::new();
    for source in &sources {
        objects.push(compile.object(&record, source, &out.join(gen::stem(source) + ".o"), &extra)?);
    }
    objects.extend(linked);
    let archive = out.join("liboneiosgpu.a");
    gen::archive(&archive, &objects)?;
    let required: Vec<&str> = REQUIRED.iter().chain(if link { REQUIRED_ADRENO.iter() } else { [].iter() }).copied().collect();
    gen::require_definitions(&ctx, &archive, &required)?;
    let mut listed = sources.to_vec();
    if link {
        listed.extend([places.here.join("OneiOSAdreno.cpp"), places.classes.clone(), places.accelerator_abi.clone(), places.package.join("DroidVMGpu.cpp"),
                       ctx.repo.join("external/AdrenoPM4/AdrenoPM4.c")]);
        listed.extend(["Accelerator", "Publish", "UserClient", "Submit", "Memory", "Cpu"].map(|name| places.adreno.join(format!("NativeAdreno{name}.cpp"))));
    }
    gen::write_objects(&ctx, &out, Some("iokit"), &listed)?;
    let pieces = if link {
        format!("linked ({CLASS} bound at its 24A446 iPhone18,2 addresses)")
    } else if compiled {
        "compiled, not linked".to_string()
    } else {
        format!("not compiled: {}", gen::first(why.as_deref().unwrap_or("?").lines().last().unwrap_or(""), 200))
    };
    println!("build-oneios-gpu: {} ({} objects); NativeAdreno pieces: {pieces}", archive.display(), objects.len());
    Ok(())
}
