//! One class of a kernel/prelink/classes.py record (IOAESAccelerator-24A446-v54.json, IOAcceleratorES-24A446-v54.json:
//! the class's metaclass, size, vtable slots, constructor and destructors as read from the iPhone18,2 kernelcache;
//! addresses only), and the bindings build-oneios-aes.py and build-oneios-gpu.py made from it the same way.

use crate::gen::{self, fail, Stubs};
use anyhow::{anyhow, Result};
use oneios_common::pyjson::Value;
use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

/// The protected constructor and the base destructor, relative to the class's complete destructor (slot 0), as in
/// every 24A446 build of the two families seen (iPad17,3 and iPhone18,2): the constructor 0x78 before it, the base
/// destructor 8 before.
pub const CONSTRUCTOR_BEFORE: u64 = 0x78;
pub const BASE_DESTRUCTOR_BEFORE: u64 = 8;

pub struct ClassRecord {
    pub file: String,
    pub kernelcache_sha256: String,
    pub cls: Value,
    /// vtable slot -> the function's address in the kernelcache
    pub table: BTreeMap<i128, u64>,
    /// linked address minus kernelcache address (the collection's slide of this class)
    pub slide: i128,
    pub meta_linked: u64,
    pub size: u64,
}

impl ClassRecord {
    /// `script` is the generator's name for its messages.
    pub fn load(path: &Path, class: &str, script: &str) -> Result<ClassRecord> {
        let record = gen::read_json(path)?;
        let file = gen::name(path);
        // record['classes'].get(CLASS) or fail(...)
        let cls = match gen::key(&record, "classes")?.get(class) {
            Some(cls) if cls.as_dict().is_some_and(|d| !d.is_empty()) => cls.clone(),
            _ => fail!("{script}: {file} has no {class}"),
        };
        let mut table = BTreeMap::new();
        for entry in gen::key_list(&cls, "slot_table")? {
            table.insert(gen::key_int(entry, "slot")?, gen::key_hex(entry, "original")?);
        }
        let meta_linked = gen::key_hex(&cls, "meta_class_linked")?;
        let slide = meta_linked as i128 - gen::key_hex(&cls, "meta_class")? as i128;
        let size = gen::key_hex(&cls, "size")?;
        Ok(ClassRecord { file, kernelcache_sha256: gen::key_str(&record, "kernelcache_sha256")?.to_string(), cls, table, slide, meta_linked, size })
    }

    pub fn slot(&self, slot: i128) -> Result<u64> {
        self.table.get(&slot).copied().ok_or_else(|| anyhow!("KeyError: {slot}"))
    }

    /// `cls.get('bundle') != bundle or int(cls['size'], 16) != size or cls['slots'] != slots`
    pub fn is_shape(&self, bundle: &str, size: u64, slots: i128) -> Result<bool> {
        Ok(self.cls.get("bundle").and_then(Value::as_str) == Some(bundle) && self.size == size && gen::key_int(&self.cls, "slots")? == slots)
    }

    /// The slots whose function is the class's own code: within 0x10000 of its complete destructor.
    pub fn own_slots(&self) -> Result<BTreeSet<i128>> {
        let first = self.slot(0)? as i128;
        Ok(self.table.iter().filter(|(_, address)| (**address as i128 - first).abs() < 0x10000).map(|(slot, _)| *slot).collect())
    }

    /// Slots 0, 1 and 7 are the record's destructors and getMetaClass.
    pub fn check_structors(&self, script: &str, class: &str) -> Result<()> {
        if self.slot(0)? != gen::key_hex(&self.cls, "destructor_complete")? || self.slot(1)? != gen::key_hex(&self.cls, "destructor_deleting")?
            || self.slot(7)? != gen::key_hex(&self.cls, "get_meta_class")? {
            fail!("{script}: {class}: slots 0, 1 and 7 are not its destructors and getMetaClass");
        }
        Ok(())
    }

    /// The protected constructor: 0x78 before the complete destructor, and one of the functions that store the vtable.
    pub fn constructor(&self, script: &str, class: &str) -> Result<u64> {
        let constructor = self.slot(0)? - CONSTRUCTOR_BEFORE;
        let mut stores = BTreeSet::new();
        for entry in gen::key_list(&self.cls, "stores_vtable")? {
            stores.insert(gen::key_hex(entry, "original")?);
        }
        if !stores.contains(&constructor) {
            fail!("{script}: {class}: no constructor stores the vtable at {constructor:#x}");
        }
        Ok(constructor)
    }

    pub fn base_destructor(&self) -> Result<u64> {
        Ok(self.slot(0)? - BASE_DESTRUCTOR_BEFORE)
    }

    /// The two assembly files: the metaclass as an absolute symbol (data), its link address and the instance size
    /// as numbers for the check at start (`<prefix>_parent_meta_link`, `<prefix>_parent_size`), and a stub per
    /// function at its address in the collection.
    pub fn bindings(&self, script_file: &str, meta_symbol: &str, prefix: &str, functions: &[(String, u64)]) -> (String, String) {
        let meta = self.meta_linked;
        let mut stubs = Stubs::new(vec![
            format!("// Generated by {script_file} from {} (kernelcache {}...): see there.", self.file, gen::first(&self.kernelcache_sha256, 16)),
            format!(".globl {meta_symbol}"),
            format!(".set {meta_symbol}, {meta:#x}"),
            ".section __DATA,__const".to_string(), ".p2align 3".to_string(),
            format!(".globl {prefix}_parent_meta_link"), format!("{prefix}_parent_meta_link: .quad {meta:#x}"),
            format!(".globl {prefix}_parent_size"), format!("{prefix}_parent_size: .long {:#x}", self.size),
            ".text".to_string()]);
        for (name, original) in functions {
            stubs.stub(name, (*original as i128 + self.slide) as u64);
        }
        stubs.text()
    }
}

/// `sorted(set)` as Python prints a list of numbers: `[0, 1, 7]`.
pub fn pylist<T: std::fmt::Display>(items: impl IntoIterator<Item = T>) -> String {
    format!("[{}]", items.into_iter().map(|i| i.to_string()).collect::<Vec<_>>().join(", "))
}
