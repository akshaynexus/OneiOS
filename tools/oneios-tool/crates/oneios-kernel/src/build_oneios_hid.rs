const CLASS: &str = "11IOHIDDevice";
const CONSTRUCTOR: &str = "__ZN11IOHIDDeviceC2EPK11OSMetaClass";
const DESTRUCTOR: &str = "__ZN11IOHIDDeviceD2Ev";
const META: &str = "__ZN11IOHIDDevice10gMetaClassE";
const VTABLE: &str = "__ZTV11IOHIDDevice";
const REQUIRED: [&str; 9] = ["_oneios_hid_input_start", "_droidvm_input_start", "_native_hid_touch_allocate", "_native_hid_input_allocate",
                             "_oneios_als_device_start", "__GLOBAL__sub_I_NativeHidInput.cpp", "__GLOBAL__sub_I_OneiOSALSDevice.cpp",
                             "_oneios_hid_parent_meta_link", CONSTRUCTOR];
const NOT_AN_OBJECT: &str = "build-oneios-hid: not an arm64 Mach-O object";

// ---- The header against the kernelcache's record ----

pub const PROBE: &str = r#"// Generated by build-oneios-hid.py: the class whose vtable is compared with the kernelcache's record.
#include "OriginalHidDeviceABI.h"
class OneiOSHidLayoutCheck : public IOHIDDevice {
	OSDeclareDefaultStructors(OneiOSHidLayoutCheck)
public:
	IOReturn newReportDescriptor(IOMemoryDescriptor **descriptor) const override;
};
OSDefineMetaClassAndStructors(OneiOSHidLayoutCheck, IOHIDDevice)
IOReturn OneiOSHidLayoutCheck::newReportDescriptor(IOMemoryDescriptor **) const { return kIOReturnUnsupported; }
"#;

/// One slot of the record: its number, its discriminator (as the record writes it, and as a number), whether its
/// function is the family's, its address as linked in kernel.kc.
pub struct Slot {
    pub slot: i128,
    pub diversity_text: String,
    pub diversity: u64,
    pub family: bool,
    pub linked: u64,
}

pub fn slots(list: &[Value]) -> Result<Vec<Slot>> {
    list.iter().map(|slot| {
        Ok(Slot { slot: gen::key_int(slot, "slot")?, diversity_text: gen::key_str(slot, "diversity")?.to_string(),
                  diversity: gen::key_hex(slot, "diversity")?, family: gen::key(slot, "family")?.as_bool().unwrap_or(false),
                  linked: gen::key_hex(slot, "linked")? })
    }).collect()
}

/// The vtable `name` of a compiled object; the run ends when the object does not define it.
pub fn vtable(object: &Object, name: &str) -> Result<Vec<Entry>> {
    match object.vtable(name)? {
        Some(table) => Ok(table),
        None => fail!("build-oneios-hid: {name} is not defined in the object"),
    }
}

/// The header's comment table: every "<slot> name (0x....)" (and "0, 1 name (0x...., 0x....)"), slot -> discriminator,
/// in the order listed. The pattern is the script's; its `(?<![\w.])` in front (no word character or dot before the
/// slot number) is checked by hand, since the regex crate has no look-behind.
pub fn comment_table(text: &str) -> Result<IndexMap<i128, u64>> {
    let pattern = Regex::new(r"(\d+)(?:, (\d+))? [A-Za-z][\w/()]*(?:\([\w, ]*\))? \((0x[0-9a-f]{4})(?:, (0x[0-9a-f]{4}))?\)").expect("a fixed pattern");
    let before = Regex::new(r"[\w.]$").expect("a fixed pattern");
    let mut listed = IndexMap::new();
    let mut at = 0;
    while let Some(found) = pattern.captures_at(text, at) {
        let whole = found.get(0).expect("group 0");
        if before.is_match(&text[..whole.start()]) {
            at = whole.start() + 1;
            continue;
        }
        let number = |group: usize| -> Result<i128> { found[group].parse().map_err(|_| anyhow!("the header's comment table: {}", &found[group])) };
        listed.insert(number(1)?, gen::hex(&found[3])?);
        if found.get(2).is_some() {
            let second = found.get(4).ok_or_else(|| anyhow!("the header's comment table names two slots and one discriminator: {}", whole.as_str()))?;
            listed.insert(number(2)?, gen::hex(second.as_str())?);
        }
        at = whole.end();
    }
    Ok(listed)
}

/// The check class's vtable against the record: returns {mangled IOHIDDevice function: slot}; stops when the header is
/// not the record's class. `layout_name` and `header` are the record's file name and the header's text.
pub fn check_header(layout: &Value, layout_name: &str, header: &str, table: &[Entry]) -> Result<IndexMap<String, usize>> {
    let slots = slots(gen::key_list(layout, "slots")?)?;
    if gen::key_hex(layout, "size")? != 0xd0 || !gen::key(layout, "abstract")?.as_bool().unwrap_or(false) {
        fail!("build-oneios-hid: {layout_name}: not the abstract 0xd0-byte class the header asserts");
    }
    if table.len() != slots.len() {
        fail!("build-oneios-hid: the header gives a vtable of {} slots, the kernelcache's has {}", table.len(), slots.len());
    }
    let owned = [0usize, 1, 7]; // destructors and getMetaClass: every class's own
    let pure: Vec<i128> = slots.iter().filter(|s| s.slot >= 168 && !s.family).map(|s| s.slot).collect();
    let mut slot_of = IndexMap::new();
    for (i, (entry, slot)) in table.iter().zip(&slots).enumerate() {
        let name = &entry.symbol;
        if entry.diversity() != slot.diversity || !entry.address() || entry.key() != 0 {
            fail!("build-oneios-hid: slot {i} ({name}): signed with {:#06x} (address diversity {}, key {}), the kernelcache's slot with {}",
                  entry.diversity(), entry.address() as u8, entry.key(), slot.diversity_text);
        }
        if owned.contains(&i) || pure.contains(&(i as i128)) {
            if !name.contains("OneiOSHidLayoutCheck") {
                fail!("build-oneios-hid: slot {i} ({name}): the check class's own function expected");
            }
        } else if name.contains(CLASS) != slot.family {
            fail!("build-oneios-hid: slot {i} ({name}): the kernelcache's slot is {}; the header declares an override the class does not have, \
                   or misses one", if slot.family { "the family's" } else { "the kernel's" });
        } else if name.contains(CLASS) && *slot_of.entry(name.clone()).or_insert(i) != i {
            fail!("build-oneios-hid: {name} fills two slots");
        }
    }
    if pure.len() != 1 {
        fail!("build-oneios-hid: one abstract slot expected, the record has {}", pylist(&pure));
    }
    let listed = comment_table(header)?;
    let family: BTreeSet<i128> = slots.iter().filter(|s| s.family).map(|s| s.slot).chain(pure.iter().copied()).collect();
    let named: BTreeSet<i128> = listed.keys().copied().collect();
    if named != family {
        fail!("build-oneios-hid: the header's comment table lists slots {} differently from the record", pylist(named.symmetric_difference(&family)));
    }
    let wrong: Vec<i128> = listed.iter().filter(|(slot, diversity)| **diversity != slots[**slot as usize].diversity).map(|(slot, _)| *slot).collect();
    if !wrong.is_empty() {
        fail!("build-oneios-hid: the header's comment table has other discriminators than the record for slots {}", pylist(&wrong));
    }
    Ok(slot_of)
}

// ---- The staged sources ----

fn gone(what: &'static str) -> impl Fn(&str) -> String {
    move |anchor| format!("build-oneios-hid: {what} no longer has exactly one `{}`", gen::first(anchor.trim(), 90))
}

/// NativeHidInput.cpp for the phone. The buttons device's report 2 gets a fifth bit, the ringer switch
/// (Telephony / Ring Enable), and takes all five from the transport's button sink (the source keeps the Home bit
/// for its own timed press and drops it from the sink's mask); the edge band is 3 mm of the phone's panel, not of
/// the iPad's; the products are named for what they are here; the edge wrapper follows a change of event driver;
/// a touch report carries its frame's scan time (handleReportWithTime, OneiOSTouchTime.inc).
pub fn staged_hid(text: String) -> Result<String> {
    gen::replace_once(text, HID, gone("NativeHidInput.cpp"))
}

/// DroidVMVirtioInput.c with the phone's side keys (OneiOSSideKeys.inc): xnuhost's one input device carries the
/// touch screen and the keys, and the source reads keys from a keyboard only. Each touch frame's scan time, which
/// xnuhost sends as EV_MSC / MSC_TIMESTAMP before the frame's SYN_REPORT, is kept while the frame is reported and
/// counted (OneiOSTouchTime.inc).
pub fn staged_transport(text: String, side_keys: &str, touch_time: &str) -> Result<String> {
    Ok(gen::replace_once(text, HID_TRANSPORT, gone("DroidVMVirtioInput.c"))? + "\n" + side_keys + "\n" + touch_time)
}

/// The assembly of the original functions' stubs and of their targets, for the IOHIDDevice names the objects import;
/// and the functions bound, by name.
pub fn bindings(layout: &Value, layout_name: &str, slot_of: &IndexMap<String, usize>, table: &[Entry], imports: &BTreeSet<String>)
                -> Result<(String, String, Vec<(String, u64)>)> {
    let slots = slots(gen::key_list(layout, "slots")?)?;
    let mut functions = Vec::new();
    for name in imports {
        if name == CONSTRUCTOR {
            functions.push((name.clone(), gen::key_hex(gen::key(layout, "constructor")?, "linked")?));
        } else if name == DESTRUCTOR {
            functions.push((name.clone(), gen::key_hex(gen::key(layout, "base_destructor")?, "linked")?));
        } else if name == META || name == VTABLE {
            continue; // data: the absolute metaclass, and the table below
        } else if let Some(slot) = slot_of.get(name) {
            functions.push((name.clone(), slots[*slot].linked));
        } else {
            fail!("build-oneios-hid: {name}: not a function of the original class the header declares (its vtable, static data or a \
                   private function cannot be bound)");
        }
    }
    let meta = gen::key_hex(layout, "meta_class_linked")?;
    let mut lines = vec![
        format!("// Generated by build-oneios-hid.py from {layout_name} (kernelcache {}...): see there.",
                gen::first(gen::key_str(layout, "kernelcache_sha256")?, 16)),
        format!(".globl {META}"), format!(".set {META}, {meta:#x}"),
        ".section __DATA,__const".to_string(), ".p2align 3".to_string(),
        ".globl _oneios_hid_parent_meta_link".to_string(), format!("_oneios_hid_parent_meta_link: .quad {meta:#x}"),
        ".globl _oneios_hid_parent_size".to_string(), format!("_oneios_hid_parent_size: .long {:#x}", gen::key_hex(layout, "size")?),
        ".text".to_string()];
    // A table under the original vtable's name, for calls by qualified name: in a kernel (-fapple-kext) a call such as
    // IOHIDDevice::start(provider) in a subclass loads the function from the named class's vtable and authenticates
    // it as that slot. The compiler reaches the table through the GOT, and a GOT entry for an absolute symbol would
    // hold the link address (no fixup slides it), so the original table cannot be named; this one has every slot
    // signed for its place here with the original discriminator: the stub of the family's function, or the kernel's
    // own function where the class inherits it. The destructors, getMetaClass and the abstract slot are never called
    // by qualified name: zero. No object's vtable pointer ever points here.
    lines.extend([".section __DATA,__const".to_string(), ".p2align 3".to_string(), format!(".globl {VTABLE}"), format!("{VTABLE}:"),
                  " .quad 0".to_string(), " .quad 0".to_string()]);
    for (entry, _) in table.iter().zip(&slots) {
        let name = &entry.symbol;
        let own = !name.contains(CLASS) && name.contains("OneiOSHidLayoutCheck");
        lines.push(if own { " .quad 0".to_string() } else { format!(" .quad {name}@AUTH(ia,{:#x},addr)", entry.diversity()) });
    }
    lines.push(".text".to_string());
    // The targets are absolute symbols of a second object: in one file the assembler would resolve the branch itself.
    let mut stubs = Stubs::new(lines);
    for (name, address) in &functions {
        stubs.stub(name, *address);
    }
    let (stubs, targets) = stubs.text();
    Ok((stubs, targets, functions))
}

/// Every owned vtable keeps the original's slots: the discriminators, and the original function wherever the
/// class does not override it. Returns the slots each owned class fills itself, by vtable name.
fn owned_slots(objects: &[PathBuf], layout: &Value, slot_of: &IndexMap<String, usize>) -> Result<IndexMap<String, Vec<usize>>> {
    let slots = slots(gen::key_list(layout, "slots")?)?;
    let mut owned = IndexMap::new();
    for path in objects {
        let data = gen::read_bytes(path)?;
        let object = Object::parse(&data, NOT_AN_OBJECT)?;
        for name in object.own_vtables() {
            let table = vtable(&object, &name)?;
            if table.len() != slots.len() {
                fail!("build-oneios-hid: {name}: {} slots, the original has {}", table.len(), slots.len());
            }
            for (i, entry) in table.iter().enumerate() {
                let symbol = &entry.symbol;
                if entry.diversity() != slots[i].diversity || !entry.address() || entry.key() != 0 {
                    fail!("build-oneios-hid: {name} slot {i} ({symbol}): not signed as the original slot");
                }
                if symbol.contains(CLASS) && slot_of.get(symbol) != Some(&i) {
                    fail!("build-oneios-hid: {name} slot {i} ({symbol}): not the original function of that slot");
                }
            }
            let class = &name["__ZTV".len()..];
            owned.insert(name.clone(), table.iter().enumerate().filter(|(_, entry)| entry.symbol.contains(class)).map(|(i, _)| i).collect());
        }
    }
    Ok(owned)
}

pub fn main() -> Result<()> {
    let ctx = Ctx::new("build-oneios-hid", "run through the kernel build")?;
    let here = ctx.repo.join("kernel/patches/oneios-hosted/hid");
    let hid_source = ctx.repo.join("external/NativeHidInput/NativeHidInput.cpp");
    let transport_source = ctx.repo.join("external/UniXNU-droidvm/package/DroidVMVirtioInput.c");
    let als_source = ctx.repo.join("drivers/brightness/OneiOSALSDevice.cpp");
    let (layout_path, header_path) = (here.join("IOHIDDevice-24A446-v54.json"), here.join("OriginalHidDeviceABI.h"));
    gen::need_files(&[ctx.repo.join("drivers/build.py"), hid_source.clone(), transport_source.clone(), als_source.clone(), layout_path.clone(),
                      header_path.clone(), here.join("OneiOSHidInput.cpp"), here.join("OneiOSSideKeys.inc"), here.join("OneiOSTouchTime.inc"),
                      ctx.records.join("iokit/DEVELOPMENT/IOPlatformExpert.cpo.json")],
                    |path| format!("build-oneios-hid: {} missing (scripts/setup/get-references.sh NativeHidInput; kernel/fetch.sh)", path.display()))?;
    let hid_text = gen::read_text(&hid_source)?;
    if !hid_text.contains("NATIVE_HID_SOURCE_API") {
        fail!("build-oneios-hid: {} is not ShengHidInput 24f1f3f or later (its arm64e source): remove external/NativeHidInput and \
               run scripts/setup/get-references.sh NativeHidInput", hid_source.display());
    }
    let layout = gen::read_json(&layout_path)?;
    let layout_name = gen::name(&layout_path);
    let out = ctx.tree.join("build/oneios-hid");
    gen::mkdirs(&out)?;
    let includes = ["-I".to_string(), gen::s(&here), "-I".to_string(), gen::s(&here.join("include")), "-I".to_string(),
                    gen::s(&ctx.repo.join("drivers/brightness"))];
    let compile = Compile { ctx: &ctx, shown: 8000 };
    let compile_source = |universe: &str, source: &Path, object: PathBuf, extra: &[&str]| -> Result<PathBuf> {
        let arguments: Vec<String> = includes.iter().cloned().chain(extra.iter().map(|e| e.to_string())).collect();
        compile.object(&ctx.record(universe)?, source, &object, &arguments)
    };

    let probe = out.join("OneiOSHidLayoutCheck.cpp");
    gen::write_text(&probe, PROBE)?;
    let probe_data = gen::read_bytes(&compile_source("iokit", &probe, out.join("OneiOSHidLayoutCheck.o"), &[])?)?;
    let table = vtable(&Object::parse(&probe_data, NOT_AN_OBJECT)?, "__ZTV20OneiOSHidLayoutCheck")?;
    let slot_of = check_header(&layout, &layout_name, &gen::read_text(&header_path)?, &table)?;
    let slot_count = gen::key_list(&layout, "slots")?.len();
    println!("build-oneios-hid: OriginalHidDeviceABI.h is the kernelcache's IOHIDDevice: {slot_count} slots with its \
              discriminators, {} functions of the family placed, 0xd0 bytes", slot_of.len());

    let staged = out.join("NativeHidInput.cpp"); // the same file name: the static initializer is named after it
    gen::write_text(&staged, &staged_hid(hid_text)?)?;
    let hid = compile_source("iokit", &staged, out.join("NativeHidInput.o"), &["-DNATIVE_HID_SOURCE_API=1"])?;
    let start = compile_source("iokit", &here.join("OneiOSHidInput.cpp"), out.join("OneiOSHidInput.o"), &[])?;
    let als = compile_source("iokit", &als_source, out.join("OneiOSALSDevice.o"), &[])?;
    // Its queue and event pages come from the kernel map (DROIDVM_INPUT_DYNAMIC), as on the iPadOS 27 board.
    let staged = out.join("DroidVMVirtioInput.c");
    gen::write_text(&staged, &staged_transport(gen::read_text(&transport_source)?, &gen::read_text(&here.join("OneiOSSideKeys.inc"))?,
                                               &gen::read_text(&here.join("OneiOSTouchTime.inc"))?)?)?;
    let transport = compile_source("mach", &staged, out.join("DroidVMVirtioInput.o"), &["-DDROIDVM_INPUT_DYNAMIC=1", "-mgeneral-regs-only"])?;
    let objcopy = gen::which("llvm-objcopy", "objcopy");
    let mut objects = vec![start, transport];
    // The classes' static initializers register them below the original class: they run inside the module load of
    // oneios_hid_input_start, not with the kernel's own initializers. Out of __mod_init_func, and global.
    for object in [hid, als] {
        let late = object.with_extension("late.o");
        gen::late_object(&objcopy, &object, &late, &["__DATA,__mod_init_func"], &format!("__GLOBAL__sub_I_{}.cpp", gen::stem(&object)))?;
        objects.push(late);
    }

    // Every function of the family gets a stub: the table for calls by qualified name (bindings) names them all.
    let mut imports: BTreeSet<String> = slot_of.keys().cloned().collect();
    for path in &objects {
        let data = gen::read_bytes(path)?;
        let object = Object::parse(&data, NOT_AN_OBJECT)?;
        imports.extend(object.undefined().filter(|name| name.contains(CLASS)).map(str::to_string));
    }
    // The metaclass is an absolute symbol: wherever it is read from (a GOT entry or the class's superClass pointer)
    // the value may be the link address. Its one use is as the superclass each static initializer passes, which
    // OneiOSHidInput.cpp corrects before the classes register; any other use (OSDynamicCast to IOHIDDevice, say)
    // would compare against an address that is wrong when the collection is slid.
    for path in &objects {
        let data = gen::read_bytes(path)?;
        if Object::parse(&data, NOT_AN_OBJECT)?.undefined().any(|name| name.contains(&format!("{CLASS}9metaClassE"))) {
            fail!("build-oneios-hid: {} uses IOHIDDevice::metaClass (OSDynamicCast to the original class): not bound", gen::name(path));
        }
    }
    let (stubs, targets, functions) = bindings(&layout, &layout_name, &slot_of, &table, &imports)?;
    objects.extend(gen::assemble(&ctx.record("iokit")?, &out, &[("IOHIDDevice-bindings", &stubs), ("IOHIDDevice-originals", &targets)])?);
    let owned = owned_slots(&objects[2..4], &layout, &slot_of)?;

    let archive = out.join("liboneioshid.a");
    gen::archive(&archive, &objects)?;
    gen::require_definitions(&ctx, &archive, &REQUIRED)?;
    gen::write_objects(&ctx, &out, None, &[hid_source, transport_source, here.join("OneiOSSideKeys.inc"), here.join("OneiOSHidInput.cpp"), als_source,
                                           header_path, layout_path])?;
    write_report(&out, &layout, &functions, &owned)?;
    let owns: Vec<String> = owned.iter().map(|(name, slots)| format!("{} owns {} slots", &name[5..], slots.len())).collect();
    println!("build-oneios-hid: {} ({} objects, {} original IOHIDDevice functions bound at their 24A446 iPhone18,2 addresses; {})",
             archive.display(), objects.len(), functions.len(), owns.join(", "));
    Ok(())
}

/// report.json: the kernelcache the record is of, each bound function's linked address, the slots each owned class
/// fills. build-oneios-net.py wrote the same file for its archive.
pub fn write_report(out: &Path, layout: &Value, functions: &[(String, u64)], owned: &IndexMap<String, Vec<usize>>) -> Result<()> {
    let mut report = Value::dict();
    report.set("kernelcache_sha256", gen::key_str(layout, "kernelcache_sha256")?);
    let mut bound = Value::dict();
    for (name, address) in functions {
        bound.set(name.clone(), format!("{address:#x}"));
    }
    report.set("bindings", bound);
    let mut owned_slots = Value::dict();
    for (name, slots) in owned {
        let mut list = Value::list();
        slots.iter().for_each(|slot| list.push(*slot));
        owned_slots.set(name.clone(), list);
    }
    report.set("owned_slots", owned_slots);
    gen::write_json(&out.join("report.json"), &report, 2)
}
