pub const CRUMBS: &str = "// Generated by build-oneios-net.py: see there.\n#pragma once\n#include <stdint.h>\n#include <sys/kpi_mbuf.h>\n\
                          void m_add_hdr_crumb(mbuf_t, uint64_t, uint64_t);\nvoid m_add_hdr_crumb_chain(mbuf_t, uint64_t, uint64_t);\n";

/// `subprocess.run(cmd, check=True, capture_output=True, text=True, timeout=900).stdout`
fn run(command: &[String]) -> Result<String> {
    let result = gen::capture(command, None, Some(900))?;
    if result.code != 0 {
        fail!("{} ended with status {}: {}", command.join(" "), result.code, result.stderr.trim_end());
    }
    Ok(result.stdout)
}

/// The family's source at its pin (headers only are used), fetched once into out/sources of the repository.
fn family(ctx: &Ctx) -> Result<PathBuf> {
    let source = ctx.repo.join("out/sources/IONetworkingFamily");
    if !source.join(".git").is_dir() {
        gen::mkdirs(source.parent().expect("a joined path"))?;
        run(&["git", "clone", "-q", "--depth", "1", "--branch", IONET_TAG, IONET_REPOSITORY, &gen::s(&source)].map(String::from))?;
    }
    if run(&["git", "-C", &gen::s(&source), "rev-parse", "HEAD"].map(String::from))?.trim() != IONET_COMMIT {
        fail!("build-oneios-net: {}: {IONET_TAG} must be {IONET_COMMIT}", source.display());
    }
    let mut found: Vec<String> = glob(&source, "cpp")?.iter().map(|path| gen::stem(path)).collect();
    found.sort();
    if found != IONET_FILES {
        fail!("build-oneios-net: {IONET_TAG}: not the twelve family sources");
    }
    Ok(source)
}

/// `folder.glob('*.<extension>')`.
fn glob(folder: &Path, extension: &str) -> Result<Vec<PathBuf>> {
    Ok(std::fs::read_dir(folder).with_context(|| format!("{}", folder.display()))?.filter_map(|entry| entry.ok().map(|e| e.path()))
        .filter(|path| path.extension().is_some_and(|e| e == extension)).collect())
}

/// `repr(text)` of a Python string without control characters.
fn pyrepr(text: &str) -> String {
    if text.contains('\'') && !text.contains('"') {
        format!("\"{}\"", text.replace('\\', "\\\\"))
    } else {
        format!("'{}'", text.replace('\\', "\\\\").replace('\'', "\\'"))
    }
}

/// A header of the iphoneos SDK the record compiles against (-isysroot), else Xcode's.
fn sdk_header(record: &Record, name: &str) -> Result<PathBuf> {
    let args = &record.arguments;
    let mut roots: Vec<String> = args.windows(2).filter(|pair| pair[0] == "-isysroot").map(|pair| pair[1].clone()).collect();
    if roots.is_empty() && which::which("xcrun").is_ok() {
        roots = vec![run(&["xcrun", "--sdk", "iphoneos", "--show-sdk-path"].map(String::from))?.trim().to_string()];
    }
    for root in &roots {
        let path = Path::new(root).join("usr/include").join(name);
        if path.is_file() {
            return Ok(path);
        }
    }
    let said = if roots.is_empty() {
        "no -isysroot in the record and no xcrun".to_string()
    } else {
        format!("[{}]", roots.iter().map(|root| pyrepr(root)).collect::<Vec<_>>().join(", "))
    };
    fail!("build-oneios-net: no {name} in the SDK ({said})")
}

/// <IOKit/network/...> for the family's headers, the SDK's TargetConditionals.h, and the mbuf crumbs header.
fn includes(out: &Path, source: &Path, record: &Record) -> Result<PathBuf> {
    let include = out.join("ionetworking-include");
    gen::mkdirs(&include.join("IOKit/network"))?;
    let mut links: Vec<(PathBuf, PathBuf)> = glob(source, "h")?.into_iter().map(|h| (include.join("IOKit/network").join(gen::name(&h)), h)).collect();
    links.push((include.join("TargetConditionals.h"), sdk_header(record, "TargetConditionals.h")?));
    for (link, target) in links {
        let _ = std::fs::remove_file(&link);
        std::os::unix::fs::symlink(&target, &link).with_context(|| format!("{}", link.display()))?;
    }
    // xnu-12377's sys/mbuf.h has inline helpers that pass an mbuf_t (the KPI's opaque struct __mbuf *) to functions
    // taking struct mbuf *; the family never calls them. Overloads taking mbuf_t, declared first, let them compile
    // (build-droidvm-devices.py's fix).
    gen::write_text(&include.join("oneios-mbuf-crumbs.h"), CRUMBS)?;
    Ok(include)
}

/// DroidVMVirtioNet.c with multicast passed: on the phone's Wi-Fi the guest needs IPv6's neighbour discovery
/// (all-nodes and solicited-node groups) and mDNS; iOS's own stack drops groups it has not joined.
pub fn staged_text(text: String) -> Result<String> {
    gen::replace_once(text, NET_TRANSPORT, |old| {
        format!("build-oneios-net: DroidVMVirtioNet.c no longer has exactly one {}", pyrepr(gen::first(old.trim(), 60)))
    })
}

/// The class a mangled member function name is qualified by (__ZN[K]<len><class>...), or None.
pub fn owner(name: &str) -> Option<&str> {
    let found = Regex::new(r"^__ZNK?(\d+)").expect("a fixed pattern").captures(name)?;
    let length: usize = found[1].parse().ok()?;
    let start = found.get(0)?.end();
    Some(name.get(start..start + length).unwrap_or(&name[start.min(name.len())..]))
}

fn in_family(name: &str) -> bool {
    owner(name).is_some_and(|class| FAMILY.contains(&class))
}

/// The probe class of a parent, as its vtable's name gives it: `symbol[len('__ZTV'):].lstrip('0123456789')`.
fn probe_class(symbol: &str) -> &str {
    symbol["__ZTV".len()..].trim_start_matches(|c: char| c.is_ascii_digit())
}

fn class_slots(layout: &Value, parent: &str) -> Result<Vec<Slot>> {
    slots(gen::key_list(gen::key(gen::key(layout, "classes")?, parent)?, "slots")?)
}

/// {mangled family function: linked address}, and per parent the probe's vtable; stops when the headers are not
/// the record's classes.
pub fn check_layout(layout: &Value, probe: &Object) -> Result<(IndexMap<String, u64>, Vec<Vec<Entry>>)> {
    let mut address_of = IndexMap::new();
    let mut tables = Vec::new();
    for (parent, _, symbol) in PARENTS {
        let slots = class_slots(layout, parent)?;
        let table = hid::vtable(probe, symbol)?;
        if table.len() != slots.len() {
            fail!("build-oneios-net: {parent}: the headers give a vtable of {} slots, the kernelcache's has {}", table.len(), slots.len());
        }
        for (i, (entry, slot)) in table.iter().zip(&slots).enumerate() {
            let name = &entry.symbol;
            if entry.diversity() != slot.diversity || !entry.address() || entry.key() != 0 {
                fail!("build-oneios-net: {parent} slot {i} ({name}): signed with {:#06x}, the kernelcache's slot with {}", entry.diversity(),
                      slot.diversity_text);
            }
            if name.contains(probe_class(symbol)) {
                continue; // the destructors, getMetaClass, the probe's override
            }
            let family = in_family(name);
            if family != slot.family {
                fail!("build-oneios-net: {parent} slot {i} ({name}): the kernelcache's slot is {}'s", if slot.family { "the family" } else { "the kernel" });
            }
            if family && *address_of.entry(name.clone()).or_insert(slot.linked) != slot.linked {
                fail!("build-oneios-net: {name}: two addresses in the record");
            }
        }
        tables.push(table);
    }
    Ok((address_of, tables))
}

/// The assembly of the stubs, the metaclasses, the parents' vtables for qualified calls, and the stubs' targets;
/// and the functions bound, in the order the script's dict had them.
pub fn bindings(layout: &Value, layout_name: &str, address_of: &IndexMap<String, u64>, tables: &[Vec<Entry>], imports: &BTreeSet<String>)
                -> Result<(String, String, IndexMap<String, u64>)> {
    let classes = gen::key(layout, "classes")?;
    let mut functions = IndexMap::new();
    for name in imports {
        let parent = owner(name).and_then(|class| PARENTS.iter().find(|(key, _, _)| *key == class));
        if let Some(address) = address_of.get(name) {
            functions.insert(name.clone(), *address);
        } else if let Some((class, mangled, _)) = parent.filter(|(_, mangled, _)| name.starts_with(&format!("__ZN{mangled}C2EPK11OSMetaClass"))) {
            let _ = mangled;
            functions.insert(name.clone(), gen::key_hex(gen::key(gen::key(classes, class)?, "constructor")?, "linked")?);
        } else if let Some((class, _, _)) = parent.filter(|(_, mangled, _)| *name == format!("__ZN{mangled}D2Ev")) {
            functions.insert(name.clone(), gen::key_hex(gen::key(gen::key(classes, class)?, "base_destructor")?, "linked")?);
        } else if PARENTS.iter().any(|(_, mangled, _)| *name == format!("__ZN{mangled}10gMetaClassE") || *name == format!("__ZTV{mangled}")) {
            continue;
        } else {
            fail!("build-oneios-net: {name}: not a virtual function, constructor or destructor of the original classes (a non-virtual \
                   function of the family has no slot to bind it by)");
        }
    }
    let mut lines = vec![format!("// Generated by build-oneios-net.py from {layout_name} (kernelcache {}...): see there.",
                                 gen::first(gen::key_str(layout, "kernelcache_sha256")?, 16))];
    for ((class, mangled, probe), table) in PARENTS.iter().zip(tables) {
        let record = gen::key(classes, class)?;
        let meta = gen::key_hex(record, "meta_class_linked")?;
        let short = if *class == "IOEthernetController" { "controller" } else { "interface" };
        lines.extend([
            format!(".globl __ZN{mangled}10gMetaClassE"), format!(".set __ZN{mangled}10gMetaClassE, {meta:#x}"),
            ".section __DATA,__const".to_string(), ".p2align 3".to_string(),
            format!(".globl _oneios_net_{short}_meta_link"), format!("_oneios_net_{short}_meta_link: .quad {meta:#x}"),
            format!(".globl _oneios_net_{short}_size"), format!("_oneios_net_{short}_size: .long {:#x}", gen::key_hex(record, "size")?),
            // The parent's table for calls by qualified name (super::start and the like): every slot signed for
            // its place here with the original discriminator, the family's functions through their stubs, the
            // kernel's by their own names; the probe's own slots (destructors, getMetaClass, the abstract one) 0.
            ".p2align 3".to_string(), format!(".globl __ZTV{mangled}"), format!("__ZTV{mangled}:"), " .quad 0".to_string(), " .quad 0".to_string()]);
        for (entry, slot) in table.iter().zip(&class_slots(layout, class)?) {
            let name = &entry.symbol;
            if name.contains(probe_class(probe)) {
                lines.push(" .quad 0".to_string());
            } else {
                if in_family(name) {
                    functions.entry(name.clone()).or_insert(slot.linked);
                }
                lines.push(format!(" .quad {name}@AUTH(ia,{:#x},addr)", entry.diversity()));
            }
        }
        lines.push(".text".to_string());
    }
    let mut stubs = Stubs::new(lines);
    let mut sorted: Vec<(&String, &u64)> = functions.iter().collect();
    sorted.sort();
    for (name, address) in sorted {
        stubs.stub(name, *address);
    }
    let (stubs, targets) = stubs.text();
    Ok((stubs, targets, functions))
}

/// Our vtables keep the originals' slots: the discriminators, and the original function wherever a class does not
/// override it. Returns the family's slots each of our classes fills itself, by vtable name.
fn owned_slots(late: &Object, layout: &Value, address_of: &IndexMap<String, u64>) -> Result<IndexMap<String, Vec<usize>>> {
    let mut owned = IndexMap::new();
    for name in late.own_vtables() {
        let table = hid::vtable(late, &name)?;
        let parent = if name.contains("Interface") { "IOEthernetInterface" } else { "IOEthernetController" };
        let slots = class_slots(layout, parent)?;
        if table.len() != slots.len() {
            fail!("build-oneios-net: {name}: {} slots, the original {parent} has {}", table.len(), slots.len());
        }
        for (i, entry) in table.iter().enumerate() {
            let symbol = &entry.symbol;
            if entry.diversity() != slots[i].diversity || !entry.address() || entry.key() != 0 {
                fail!("build-oneios-net: {name} slot {i} ({symbol}): not signed as the original slot");
            }
            if in_family(symbol) && address_of.get(symbol) != Some(&slots[i].linked) {
                fail!("build-oneios-net: {name} slot {i} ({symbol}): not the original function of that slot");
            }
        }
        owned.insert(name.clone(), table.iter().enumerate().filter(|(i, entry)| !in_family(&entry.symbol) && slots[*i].family).map(|(i, _)| i).collect());
    }
    Ok(owned)
}

pub fn main() -> Result<()> {
    let ctx = Ctx::new("build-oneios-net", "run through the kernel build")?;
    let here = ctx.repo.join("kernel/patches/oneios-hosted/net");
    let xnu = ctx.tree.join(".cache/xnu-work");
    let package = ctx.repo.join("external/UniXNU-droidvm/package");
    let (transport_source, start, subtype_source) = (package.join("DroidVMVirtioNet.c"), here.join("OneiOSWifi.cpp"), here.join("OneiOSWifiLayout.cpp"));
    let (layout_path, proto) = (here.join("IONetworking-24A446-v54.json"), ctx.repo.join("drivers/net/oneios_wifi_proto.h"));
    // (the script also asked for build-oneios-hid.py here: it imported that script's Mach-O readers, macho_object.rs now)
    for path in [ctx.repo.join("drivers/build.py"), transport_source.clone(), start.clone(), subtype_source.clone(), proto.clone(), layout_path.clone(),
                 package.join("DroidVMDmaRegion.h"), ctx.records.join("iokit/DEVELOPMENT/IOPlatformExpert.cpo.json"), xnu.join("bsd")] {
        if !path.exists() {
            fail!("build-oneios-net: {} missing (scripts/setup/get-references.sh UniXNU-droidvm; kernel/fetch.sh)", path.display());
        }
    }
    let layout = gen::read_json(&layout_path)?;
    let out = ctx.tree.join("build/oneios-net");
    gen::mkdirs(&out)?;
    let iokit = ctx.record("iokit")?;
    let source = family(&ctx)?;
    let include = includes(&out, &source, &iokit)?;
    // The family's headers as the family itself saw them (__PRIVATE_SPI__ changes IONetworkController's and
    // IONetworkInterface's layout); sys/systm.h first, the bsd source tree last for private headers the export set
    // leaves out (build-droidvm-devices.py's universe).
    let universe: Vec<String> = ["-DLIBKERN_CONSUMED=", "-DLIBKERN_RETURNS_RETAINED=", "-DLIBKERN_RETURNS_NOT_RETAINED=", "-DLIBKERN_CONSUMES_THIS=",
                                 "-include", "sys/systm.h", "-include", &gen::s(&include.join("oneios-mbuf-crumbs.h")), "-I", &gen::s(&xnu.join("bsd")),
                                 "-D__PRIVATE_SPI__", "-isystem", &gen::s(&include), "-Wno-c99-designator", "-Wno-reorder-init-list",
                                 "-Wno-deprecated-enum-enum-conversion", "-Wno-unnecessary-virtual-specifier", "-Wno-macro-redefined"]
        .iter().map(|flag| flag.to_string()).collect();
    let compile = Compile { ctx: &ctx, shown: 8000 };
    let base = ["-I".to_string(), gen::s(&xnu.join("osfmk")), "-I".to_string(), gen::s(&package), "-I".to_string(), gen::s(&ctx.repo.join("drivers/net"))];
    let compile_source = |kind: &str, src: &Path, object: PathBuf, extra: &[String]| -> Result<PathBuf> {
        let arguments: Vec<String> = base.iter().chain(extra).cloned().collect();
        compile.object(&ctx.record(kind)?, src, &object, &arguments)
    };

    let probe = out.join("OneiOSNetCheck.cpp");
    gen::write_text(&probe, PROBE)?;
    let probe_data = gen::read_bytes(&compile_source("iokit", &probe, out.join("OneiOSNetCheck.o"), &universe)?)?;
    let (address_of, tables) = check_layout(&layout, &Object::parse(&probe_data, NOT_AN_OBJECT)?)?;
    let counted: Vec<String> = PARENTS.iter().zip(&tables).map(|((class, _, _), table)| format!("{class} {} slots", table.len())).collect();
    println!("build-oneios-net: the IONetworkingFamily-188 headers are the kernelcache's classes: {}, {} functions of the family placed",
             counted.join(", "), address_of.len());

    let wifi = compile_source("iokit", &start, out.join("OneiOSWifi.o"), &universe)?;
    let late = wifi.with_extension("late.o");
    // The classes' static initializer registers them below the original classes: it runs inside oneios_net_start's
    // module load, not with the kernel's own initializers. Out of __mod_init_func, and global.
    gen::late_object(&gen::which("llvm-objcopy", "objcopy"), &wifi, &late, &["__DATA,__mod_init_func"], "__GLOBAL__sub_I_OneiOSWifi.cpp")?;
    let with_keyword: Vec<String> = universe.iter().cloned().chain(["-Wno-keyword-macro".to_string()]).collect();
    let subtype = compile_source("iokit", &subtype_source, out.join("OneiOSWifiLayout.o"), &with_keyword)?;
    let staged = out.join("DroidVMVirtioNet.c");
    gen::write_text(&staged, &staged_text(gen::read_text(&transport_source)?)?)?;
    let transport = compile_source("mach", &staged, out.join("DroidVMVirtioNet.o"), &["-DDROIDVM_DEVICE_DYNAMIC=1".to_string()])?;
    let mut objects = vec![late.clone(), subtype, transport];
    let sections = gen::capture(&[gen::which("llvm-objdump", "objdump"), "-h".into(), gen::s(&late)], None, None)?.stdout;
    if sections.contains("__mod_init_func") {
        fail!("build-oneios-net: OneiOSWifi.late.o still has a __mod_init_func section: its classes would register twice");
    }

    let late_data = gen::read_bytes(&late)?;
    let late_object = Object::parse(&late_data, NOT_AN_OBJECT)?;
    let owned = owned_slots(&late_object, &layout, &address_of)?;
    let mut imports = BTreeSet::new();
    for path in &objects {
        let data = gen::read_bytes(path)?;
        let object = Object::parse(&data, NOT_AN_OBJECT)?;
        imports.extend(object.undefined().filter(|name| in_family(name)).map(str::to_string));
        if object.undefined().any(|name| name.ends_with("9metaClassE") && in_family(name)) {
            fail!("build-oneios-net: {} uses a family class's metaClass (OSDynamicCast to an original class): not bound", gen::name(path));
        }
    }
    imports.extend(late_object.undefined().filter(|name| PARENTS.iter().any(|(_, mangled, _)| name.starts_with(&format!("__ZTV{mangled}"))))
        .map(str::to_string));
    let layout_name = gen::name(&layout_path);
    let (stubs, targets, functions) = bindings(&layout, &layout_name, &address_of, &tables, &imports)?;
    objects.extend(gen::assemble(&iokit, &out, &[("IONetworking-bindings", &stubs), ("IONetworking-originals", &targets)])?);

    let archive = out.join("liboneiosnet.a");
    gen::archive(&archive, &objects)?;
    gen::require_definitions(&ctx, &archive, &REQUIRED)?;
    // The staged source in the script's place (the module comment).
    let mut list = Value::list();
    for path in [transport_source, start, subtype_source, proto, layout_path, staged] {
        list.push(gen::source_entry(ctx.relative(&path).unwrap_or_else(|_| gen::s(&path)), None, &path)?);
    }
    let mut headers = Value::dict();
    headers.set("tag", IONET_TAG);
    headers.set("commit", IONET_COMMIT);
    let mut listing = Value::dict();
    listing.set("ionetworking_headers", headers);
    listing.set("sources", list);
    gen::write_json(&out.join("objects.json"), &listing, 2)?;
    let bound: Vec<(String, u64)> = functions.iter().map(|(name, address)| (name.clone(), *address)).collect();
    write_report(&out, &layout, &bound, &owned)?;
    let owns: Vec<String> = owned.iter().map(|(name, slots)| format!("{} owns {} of the family's slots", &name[5..], slots.len())).collect();
    println!("build-oneios-net: {} ({} objects, {} original functions bound at their 24A446 iPhone18,2 addresses; {})", archive.display(),
             objects.len(), functions.len(), owns.join(", "));
    Ok(())
}
