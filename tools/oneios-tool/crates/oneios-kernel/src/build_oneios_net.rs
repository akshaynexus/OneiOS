const IONET_TAG: &str = "IONetworkingFamily-188";
const IONET_COMMIT: &str = "bb910e2b458939f6b1f53c0fa6907f258b431ea4";
const IONET_REPOSITORY: &str = "https://github.com/apple-oss-distributions/IONetworkingFamily.git";
const IONET_FILES: [&str; 12] = ["IOEthernetController", "IOEthernetInterface", "IOKernelDebugger", "IOMbufMemoryCursor", "IONetworkController",
                                 "IONetworkData", "IONetworkInterface", "IONetworkMedium", "IONetworkStack", "IONetworkUserClient", "IOOutputQueue",
                                 "IOPacketQueue"];
const REQUIRED: [&str; 9] = ["_oneios_net_start", "_droidvm_net_start", "_droidvm_net_tx_frame", "_droidvm_net_if_attach", "_droidvm_net_if_input",
                             "__GLOBAL__sub_I_OneiOSWifi.cpp", "_oneios_net_set_subtype", "_oneios_net_controller_meta_link",
                             "_oneios_net_interface_meta_link"];
/// The original classes: the record's key, the name as mangled, the probe class's vtable.
const PARENTS: [(&str, &str, &str); 2] = [("IOEthernetController", "20IOEthernetController", "__ZTV24OneiOSNetCheckController"),
                                          ("IOEthernetInterface", "19IOEthernetInterface", "__ZTV23OneiOSNetCheckInterface")];
/// The family's classes a mangled name can be qualified by; any other qualifier is the kernel's.
const FAMILY: [&str; 11] = ["IOEthernetController", "IOEthernetInterface", "IONetworkController", "IONetworkInterface", "IONetworkMedium",
                            "IONetworkData", "IOOutputQueue", "IOKernelDebugger", "IONetworkStack", "IOMbufMemoryCursor", "IOPacketQueue"];
const NOT_AN_OBJECT: &str = "build-oneios-hid: not an arm64 Mach-O object";

