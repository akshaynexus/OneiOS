/// The probes of other archives the staged probe would start: not ours.
const NO_PROBE: [&str; 5] = ["native_keystore_probe", "sheng_cpufreq_probe", "sheng_gpu_power_probe", "native_touch_probe", "native_hid_input_probe"];
/// Prototypes of the original slots the owned backend overrides or calls; every other slot is an opaque dispatch target.
const PROTOTYPES: [(&str, &str); 13] = [
    ("isMainDisplay", "bool isMainDisplay()"), ("getDotPitch", "IOReturn getDotPitch(uint32_t *)"),
    ("supportedFrameInfo", "IOReturn supportedFrameInfo(uint32_t,uint32_t *,char *,uint32_t *)=0"),
    ("getDisplayDimensions", "void getDisplayDimensions(uint32_t *,uint32_t *)"), ("startHardware", "bool startHardware()"),
    ("kickSwapQueue", "void kickSwapQueue()"), ("completeCurrentSwap", "void completeCurrentSwap()"),
    ("validateSwap", "bool validateSwap(const OriginalLegacySwapRequest *)"),
    ("getRefreshAttributes", "bool getRefreshAttributes(uint64_t *,bool)"),
    ("collectCompletionReports", "IOReturn collectCompletionReports(uint32_t,void *,uint32_t *,uint32_t)=0"),
    ("applyStateRequest", "int applyStateRequest(OriginalLegacyStateRequest *,bool)"),
    ("cancelSwapsAfterTimeout", "bool cancelSwapsAfterTimeout()"),
    ("create_default_fb_surface", "void create_default_fb_surface()")];

/// The probe's entries are OneiOSDisplay.cpp's to wrap, and the probes of other archives it starts are not ours.
fn probe_defines() -> Vec<String> {
    ["-DNATIVE_LEGACY_PLAIN_NUB=1", "-DPE_parse_boot_argn=oneios_display_boot_arg",
     "-Dnative_legacy_display_probe=oneios_native_legacy_display_probe",
     "-Dnative_legacy_display_late_probe=oneios_native_legacy_display_late_probe"].iter().map(|d| d.to_string())
        .chain(NO_PROBE.iter().map(|name| format!("-D{name}=oneios_display_no_probe"))).collect()
}

fn require(value: bool, why: impl FnOnce() -> String) -> Result<()> {
    if !value {
        fail!("build-oneios-display: {}", why());
    }
    Ok(())
}

/// clang ptrauth_string_discriminator: SipHash-2-4 with the fixed key, modulo 0xffff, plus one.
pub fn discriminator(name: &str) -> u64 {
    let key = [0xb5, 0xd4, 0xc9, 0xeb, 0x79, 0x10, 0x4a, 0x79, 0x6f, 0xec, 0x8b, 0x1b, 0x42, 0x87, 0x81, 0xd4];
    SipHasher24::new_with_key(&key).hash(name.as_bytes()) % 0xffff + 1
}

/// The record (legacy-display-24A446-v54.json) with its slots as numbers: (the function's address, the diversity).
pub struct Abi {
    pub value: Value,
    pub file: String,
    pub slots: Vec<(u64, u64)>,
}

impl Abi {
    pub fn load(path: &Path) -> Result<Abi> {
        let value = gen::read_json(path)?;
        let mut slots = Vec::new();
        for slot in gen::key_list(&value, "slots")? {
            let pair = slot.as_list().filter(|p| p.len() == 2).ok_or_else(|| anyhow!("a slot is not [target, diversity]"))?;
            slots.push((gen::hex(pair[0].as_str().unwrap_or(""))?, gen::hex(pair[1].as_str().unwrap_or(""))?));
        }
        Ok(Abi { value, file: gen::name(path), slots })
    }

    /// The abstract slots: the ones whose target is slot 214's (`__cxa_pure_virtual`).
    pub fn pure(&self) -> BTreeSet<usize> {
        let target = self.slots[214].0;
        self.slots.iter().enumerate().filter(|(_, slot)| slot.0 == target).map(|(i, _)| i).collect()
    }

    /// The family's code: `range(family_text[0], family_text[1])`.
    fn family(&self) -> Result<std::ops::Range<u64>> {
        let text = gen::key_list(&self.value, "family_text")?;
        Ok(gen::hex(text[0].as_str().unwrap_or(""))?..gen::hex(text[1].as_str().unwrap_or(""))?)
    }

    fn slide(&self) -> Result<u64> {
        gen::key_hex(&self.value, "collection_slide")
    }
}

/// `str(value)` of a record's number or string, as an f-string writes it.
fn shown(value: &Value) -> String {
    match value {
        Value::Str(text) => text.clone(),
        Value::Int(number) => number.to_string(),
        other => oneios_common::pyjson::dumps(other, None, false),
    }
}

/// OriginalLegacyFramebufferABI.h, as Droid-VM's build-droidvm-legacy-display.py writes it.
pub fn header(abi: &Abi) -> Result<String> {
    let value = &abi.value;
    let (display, request) = (gen::key(value, "display")?, gen::key(value, "request")?);
    let methods = gen::key(value, "methods")?;
    let pure = abi.pure();
    let mut by_slot = BTreeMap::new();
    for (name, slot) in methods.as_dict().unwrap_or(&[]) {
        by_slot.insert(slot.as_int().unwrap_or(-1), name.as_str());
    }
    let mut renames = String::new();
    for (base, pair) in gen::key(value, "names")?.as_dict().unwrap_or(&[]) {
        let pair = pair.as_list().filter(|p| p.len() == 2).ok_or_else(|| anyhow!("names: {base} is not [name, suffix]"))?;
        let (name, suffix) = (pair[0].as_str().unwrap_or(""), pair[1].as_str().unwrap_or(""));
        let mangled = format!("_ZN25{CLASS}{}{name}{suffix}", name.chars().count());
        // abi['methods'].get(base) or int(base[len('opaque'):])
        let slot = match methods.get(base).and_then(Value::as_int).filter(|slot| *slot != 0) {
            Some(slot) => slot as usize,
            None => base.get("opaque".len()..).and_then(|n| n.parse().ok()).ok_or_else(|| anyhow!("names: {base} names no slot"))?,
        };
        require(abi.slots.get(slot).is_some_and(|s| s.1 == discriminator(&mangled)),
                || format!("the reviewed name {name} has not the diversity of slot {slot}"))?;
        renames += &format!("#define {base} {name}\n");
    }
    let leaves = gen::key_list(value, "leaves")?.iter().map(|i| format!("LEAF({})", shown(i))).collect::<Vec<_>>().join(" ");
    let instance_size = gen::key_str(value, "instance_size")?;
    let field = |of: &Value, name: &str| of.get(name).map(shown).unwrap_or_default();
    let mut text = display_header::template(&abi.file, CLASS, instance_size, &leaves, &renames, |name| field(display, name),
                                            |name| field(request, name));
    for i in 168..abi.slots.len() {
        if let Some(method) = by_slot.get(&(i as i128)) {
            let prototype = PROTOTYPES.iter().find(|(name, _)| name == method).ok_or_else(|| anyhow!("KeyError: {method:?}"))?.1;
            text += &format!(" virtual {prototype};\n");
        } else if pure.contains(&i) {
            text += &format!(" virtual __attribute__((noreturn)) void opaque{i}()=0;\n");
        } else {
            text += &format!(" virtual __attribute__((deprecated(\"Unclassified ABI: never call from source\"))) void opaque{i}();\n");
        }
    }
    text += &format!("}};\nstatic_assert(sizeof({CLASS})=={instance_size},\"Actual original instance extent\");\n");
    Ok(text)
}

/// What `bind` finds: the original functions' linked addresses by name, the slots the backend owns, the slots that
/// are the kernel's own, and the name each slot of the compiled table holds.
pub struct Bound {
    pub bindings: BTreeMap<String, u64>,
    pub owned: Vec<usize>,
    pub native: Vec<usize>,
    pub compiled: Vec<String>,
}

/// Checks the owned class's compiled vtable against the original slots; returns name -> linked address.
pub fn bind(data: &[u8], abi: &Abi) -> Result<Bound> {
    let (slots, pure, slide) = (&abi.slots, abi.pure(), abi.slide()?);
    let object = Object::parse(data, "build-oneios-display: NativeLegacyDisplay.o is not an arm64 Mach-O object")?;
    let vtable = object.symbols.iter().find(|sym| sym.name == "__ZTV19NativeLegacyDisplay").map(|sym| sym.value)
        .ok_or_else(|| anyhow!("build-oneios-display: NativeLegacyDisplay.o defines no __ZTV19NativeLegacyDisplay"))?;
    let entries = object.signed_pointers(vtable)?;
    let compiled: Vec<_> = (0..slots.len()).map(|i| entries.get(&(vtable + 16 + i as u64 * 8))).collect();
    require(compiled.iter().all(Option::is_some) && !entries.contains_key(&(vtable + 16 + slots.len() as u64 * 8)),
            || format!("the owned vtable has not exactly {} entries", slots.len()))?;
    let compiled: Vec<_> = compiled.into_iter().flatten().collect();
    for (i, entry) in compiled.iter().enumerate() {
        let word = entry.word;
        require(word >> 63 != 0 && entry.address() && entry.key() == 0 && entry.diversity() == slots[i].1,
                || format!("slot {i} ({}) is not signed with IA, address diversity and the original diversity {:#x}", entry.symbol, slots[i].1))?;
    }
    let family = abi.family()?;
    let mut bindings = BTreeMap::new();
    for (name, va) in gen::key(&abi.value, "bindings")?.as_dict().unwrap_or(&[]) {
        bindings.insert(name.clone(), gen::hex(va.as_str().unwrap_or(""))? + slide);
    }
    let (mut owned, mut native) = (Vec::new(), Vec::new());
    for (i, entry) in compiled.iter().enumerate() {
        let name = &entry.symbol;
        if name.starts_with("__ZN19NativeLegacyDisplay") || name.starts_with("__ZNK19NativeLegacyDisplay") {
            owned.push(i);
        } else if name.contains(&format!("25{CLASS}")) {
            require(!pure.contains(&i), || format!("slot {i} is abstract in the original and the backend does not implement it"))?;
            let linked = slots[i].0 + slide;
            require(bindings.get(name).is_none_or(|address| *address == linked), || format!("{name} names two original addresses"))?;
            bindings.insert(name.clone(), linked);
        } else {
            require(i < 168 && !family.contains(&slots[i].0),
                    || format!("slot {i} ({name}) is the kernel's here and the family's in the original"))?;
            native.push(i);
        }
    }
    require(pure.iter().all(|slot| owned.contains(slot)), || "an original abstract slot is not implemented by the owned backend".to_string())?;
    let unbound: Vec<&str> = object.undefined().filter(|name| name.contains(CLASS) && !bindings.contains_key(*name)).collect::<BTreeSet<_>>()
        .into_iter().collect();
    require(unbound.is_empty(), || format!("original-class imports without a binding: {}", unbound.join(", ")))?;
    Ok(Bound { bindings, owned, native, compiled: compiled.iter().map(|entry| entry.symbol.clone()).collect() })
}

/// The bindings: stubs to the original functions, the parent's metaclass as numbers, and the parent's vtable.
///
/// The vtable is ours, not the original's. The kernel is compiled as a kernel extension is (-fapple-kext): a
/// qualified call of a parent's virtual method (IOMobileFramebufferLegacy::start(provider)) is made through the
/// parent's vtable, loaded by address. The original table's address would be an absolute symbol, whose value is
/// the link address and is wrong under xnuhost's slide; and its entries are signed for their own addresses. So the
/// archive defines the symbol itself: the same 379 slots, each a pointer the linker signs for this table (IA, the
/// slot's address, the slot's diversity) to a stub that branches to the original function, or to the kernel's own
/// method where the family inherits it. The original objects never see this table: their constructor stores the
/// original one, and the owned class's own table follows it.
pub fn assembly(abi: &Abi, bound: &Bound) -> Result<(String, String)> {
    let (slide, family, pure) = (abi.slide()?, abi.family()?, abi.pure());
    let mut bindings = bound.bindings.clone();
    let meta = bindings.remove(META).ok_or_else(|| anyhow!("KeyError: {META:?}"))?;
    bindings.remove(&format!("__ZTV25{CLASS}"));
    let mut table = vec![".section __DATA,__const".to_string(), ".p2align 3".to_string(), format!(".globl __ZTV25{CLASS}"),
                         format!("__ZTV25{CLASS}:"), " .quad 0".to_string(), " .quad 0".to_string()];
    for (i, (target, diversity)) in abi.slots.iter().enumerate() {
        let name = if pure.contains(&i) {
            "___cxa_pure_virtual".to_string()
        } else if family.contains(target) {
            let name = format!("_oneios_display_original_slot{i}");
            bindings.insert(name.clone(), target + slide);
            name
        } else if bound.compiled[i].contains("19NativeLegacyDisplay") {
            "___cxa_pure_virtual".to_string() // the kernel's method, overridden by the backend: never called through the parent
        } else {
            bound.compiled[i].clone() // the kernel's own (IOService's), as the family inherits it
        };
        table.push(format!(" .quad {name}@AUTH(ia,{diversity:#x},addr)"));
    }
    let mut lines = vec![
        format!("// Generated by build-oneios-display.py from {} (kernelcache {}...): see there.", abi.file,
                gen::first(gen::key_str(&abi.value, "kernelcache_sha256")?, 16)),
        format!(".globl {META}"), format!(".set {META}, {meta:#x}"),
        ".section __DATA,__const".to_string(), ".p2align 3".to_string(),
        ".globl _oneios_display_parent_meta_link".to_string(), format!("_oneios_display_parent_meta_link: .quad {meta:#x}"),
        ".globl _oneios_display_parent_size".to_string(),
        format!("_oneios_display_parent_size: .long {:#x}", gen::key_hex(&abi.value, "instance_size")?)];
    lines.extend(table);
    lines.push(".text".to_string());
    // The targets are absolute symbols of a second object: in one file the assembler would resolve the branch itself;
    // across objects it leaves a branch relocation, which XnuPrelink's emitter retargets.
    let mut stubs = Stubs::new(lines);
    for (name, address) in &bindings {
        stubs.stub(name, *address);
    }
    Ok(stubs.text())
}

/// LegacyDisplayProbe.cpp with the lines of staged/display.rs.
pub fn staged_text(text: String) -> Result<String> {
    gen::replace_once(text, DISPLAY, |anchor| format!("build-oneios-display: LegacyDisplayProbe.cpp no longer has exactly one {}", anchor.trim()))
}

/// DroidVMVirtioGpuDisplay.cpp with the lines of staged/display.rs's SCANOUT: half-float surfaces scanned out as such.
pub fn staged_scanout(text: String) -> Result<String> {
    gen::replace_once(text, SCANOUT, |anchor| {
        format!("build-oneios-display: DroidVMVirtioGpuDisplay.cpp no longer has exactly one {}", anchor.trim())
    })
}

fn list<T: Into<Value>>(items: impl IntoIterator<Item = T>) -> Value {
    let mut value = Value::list();
    items.into_iter().for_each(|item| value.push(item));
    value
}

pub fn main() -> Result<()> {
    let ctx = Ctx::new("build-oneios-display", "run through the kernel build")?;
    let here = ctx.repo.join("kernel/patches/oneios-hosted/display");
    let display = ctx.repo.join("external/NativeMobileDisplay");
    let package = ctx.repo.join("external/UniXNU-droidvm/package");
    let adreno = ctx.repo.join("external/NativeAdreno");
    let abi_path = here.join("legacy-display-24A446-v54.json");
    let out = ctx.tree.join("build/native-legacy-display");
    let sources = [display.join("NativeLegacyDisplay.cpp"), display.join("NativeLegacyRequest.h"), display.join("NativeGOPPresenter.cpp"),
                   display.join("NativeGOPWire.h"), display.join("NativeHalfCodes.h"), package.join("LegacyDisplayProbe.cpp"),
                   package.join("DroidVMVirtioGpuDisplay.cpp"), package.join("DroidVMVirtioGpu.h"), here.join("OneiOSDisplay.cpp"), abi_path.clone()];
    let mut needed = vec![ctx.repo.join("drivers/sources.txt"), ctx.records.join("iokit/DEVELOPMENT/IOPlatformExpert.cpo.json")];
    needed.extend(sources.iter().cloned());
    gen::need_files(&needed, |path| format!("build-oneios-display: {} missing (scripts/setup/get-references.sh NativeMobileDisplay UniXNU-droidvm; \
                                             {} is made by port-legacy-display.py)", path.display(), gen::name(&abi_path)))?;
    let abi = Abi::load(&abi_path)?;
    gen::mkdirs(&out)?;
    let record = ctx.record("iokit")?;
    gen::write_text(&out.join("OriginalLegacyFramebufferABI.h"), &header(&abi)?)?;
    let objcopy = gen::which("llvm-objcopy", "objcopy");
    let compile = Compile { ctx: &ctx, shown: 8000 };
    let osfmk = ["-I".to_string(), gen::s(&ctx.tree.join(".cache/xnu-work/osfmk"))];
    let compile_cpp = |source: &Path, extra: &[String]| -> Result<PathBuf> {
        let arguments: Vec<String> = osfmk.iter().chain(extra).cloned().collect();
        compile.object(&record, source, &out.join(gen::stem(source) + ".o"), &arguments)
    };
    // A class's static initializer registers it: it must run inside the probe's module load, not with the kernel's own.
    let late = |object: PathBuf| -> Result<PathBuf> {
        let late = object.with_extension("late.o");
        gen::late_object(&objcopy, &object, &late, &["__DATA,__mod_init_func"], &format!("__GLOBAL__sub_I_{}.cpp", gen::stem(&object)))?;
        Ok(late)
    };
    let flags = |items: &[&str]| -> Vec<String> { items.iter().map(|item| item.to_string()).collect() };
    let (out_s, display_s, package_s) = (gen::s(&out), gen::s(&display), gen::s(&package));

    let native = compile_cpp(&display.join("NativeLegacyDisplay.cpp"),
                             &flags(&["-I", &out_s, "-I", &display_s, "-DPE_parse_boot_argn=oneios_display_boot_arg"]))?;
    let bound = bind(&gen::read_bytes(&native)?, &abi)?;
    let staged = out.join("LegacyDisplayProbe.cpp");
    let mut objects = vec![late(native)?, late(compile_cpp(&display.join("NativeGOPPresenter.cpp"), &flags(&["-I", &display_s]))?)?];
    gen::write_text(&staged, &staged_text(gen::read_text(&package.join("LegacyDisplayProbe.cpp"))?)?)?;
    objects.push(compile_cpp(&staged, &flags(&["-I", &package_s]).into_iter().chain(probe_defines()).collect::<Vec<_>>())?);
    // DYNAMIC as the transport in liboneiosgpu.a: its scratch entries are allocated when the display starts. Staged with
    // the scanout format of each surface (staged/display.rs SCANOUT).
    let scanout = out.join("DroidVMVirtioGpuDisplay.cpp");
    gen::write_text(&scanout, &staged_scanout(gen::read_text(&package.join("DroidVMVirtioGpuDisplay.cpp"))?)?)?;
    objects.push(compile_cpp(&scanout, &flags(&["-I", &package_s, "-I", &gen::s(&adreno), "-DDROIDVM_VIRTIO_GPU_DYNAMIC=1"]))?);
    objects.push(compile_cpp(&here.join("OneiOSDisplay.cpp"), &[])?);
    let (stubs, targets) = assembly(&abi, &bound)?;
    objects.extend(gen::assemble(&record, &out, &[(&format!("{CLASS}-bindings"), &stubs), (&format!("{CLASS}-originals"), &targets)])?);
    let archive = out.join("libNativeLegacyDisplay.late.a");
    gen::archive(&archive, &objects)?;
    gen::require_definitions(&ctx, &archive, &REQUIRED)?;

    // UniXNU's kernel build reads this: the archive's hash, and sources by a path under the tree (ours are not there).
    let mut report = Value::dict();
    report.set("archive_sha256", gen::sha256(&archive)?);
    report.set("source_sha256", Value::dict());
    report.set("kernelcache_sha256", gen::key_str(&abi.value, "kernelcache_sha256")?);
    let mut hashes = Value::dict();
    for path in &sources {
        hashes.set(ctx.relative(path)?, gen::sha256(path)?);
    }
    report.set("oneios_sources", hashes);
    let mut addresses = Value::dict();
    for (name, address) in &bound.bindings {
        addresses.set(name.clone(), format!("{address:#x}"));
    }
    report.set("bindings", addresses);
    report.set("virtual_entries", abi.slots.len());
    report.set("owned_entries", list(bound.owned.iter().copied()));
    report.set("inherited_native_entries", list(bound.native.iter().copied()));
    report.set("original_instructions_modified", false);
    gen::write_json(&out.join("build-report.json"), &report, 2)?;
    gen::write_objects(&ctx, &out, Some("iokit"), &sources)?;
    println!("build-oneios-display: {} ({} objects; {CLASS}: {} owned slots, {} of the kernel, {} original bindings at their 24A446 \
              iPhone18,2 addresses)", archive.display(), objects.len(), bound.owned.len(), bound.native.len(), bound.bindings.len());
    Ok(())
}
