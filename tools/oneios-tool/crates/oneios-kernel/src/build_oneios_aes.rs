//! `oneios-tool kernel gen aes` (was kernel/patches/oneios-hosted/aes/build-oneios-aes.py).
//!
//! The hosted kernel's software AES archive, built between the two kernel passes from the compile records of the first:
//!
//!   build/oneios-aes/liboneiosaes.a   OneiOSSoftwareAES.cpp (the patch folder: oneios_software_aes_start), UniXNU's
//!                                     SoftwareAES NativeAES.cpp with Droid-VM's software hardware keys
//!                                     (UniXNU-droidvm package/SoftwareAESKeys.inc, staged as its devices build does),
//!                                     and the generated bindings of its parent class
//!
//! Why: AppleImage4's start waits for an IOAESAccelerator, and with it IOResources' matching, the BSD disk nodes and
//! the root volume (OneiOSSoftwareAES.cpp). NativeAES subclasses the original IOAESAccelerator of the kernel
//! collection's com.apple.iokit.IOCryptoAcceleratorFamily.
//!
//! The bindings come from IOAESAccelerator-24A446-v54.json in the patch folder (kernel/prelink/classes.py's output:
//! the class's metaclass, size, vtable slots, constructor and destructors as read from the iPhone18,2 kernelcache;
//! addresses only). For each function of the parent that NativeAES's code or vtable names, a stub in kernel text:
//!       <name>:  bti c ; b <name>.original        with <name>.original an absolute symbol at the function's address
//!                                                 in the collection
//! which XnuPrelink's emitter retargets when it places the kernel (PC-relative, so right at any slide). The metaclass
//! is data: an absolute symbol, plus its address and the instance size as numbers for the check at start.
//! Which slot is which method is OriginalAESABI.h's order (SoftwareAES), the same as in Droid-VM's
//! SoftwareAES-24A446.S for the iPad: IOService's 168 slots, of which the class overrides 0, 1 (destructors),
//! 7 (getMetaClass), 86 (start), 111 (getWorkLoop) and 117 (callPlatformFunction), then its own 13. The generator
//! refuses a class whose table does not have that shape.
//!
//! Force-loaded by CONFIG_XNU_EXTRA_LD_ARCHIVES and started from oneios_board_late_start (0008-software-aes.patch).
//! kernel/build-hosted.sh adds it to the board's archives of the build's device repository.
//! Run by UniXNU's driver in the build tree, with UNIXNU_DEVICE = the device repository. No Apple file is read.
//!
//! The generated files say "Generated by build-oneios-aes.py": the script this module replaced. The text is
//! kept so that the files stay the ones the script wrote (tests/kernelgen/golden).

use crate::class_record::{pylist, ClassRecord};
use crate::gen::{self, fail, Compile, Ctx};
use anyhow::Result;
use std::path::{Path, PathBuf};

const REQUIRED: [&str; 5] = ["_oneios_software_aes_start", "__GLOBAL__sub_I_NativeAES.cpp", "__ZN9NativeAES10gMetaClassE",
                             "_oneios_aes_parent_meta_link", "__ZN16IOAESAcceleratorC2EPK11OSMetaClass"];
const CLASS: &str = "IOAESAccelerator";
/// vtable slot -> symbol
const SLOTS: [(i128, &str); 19] = [
    (0, "__ZN16IOAESAcceleratorD1Ev"),
    (1, "__ZN16IOAESAcceleratorD0Ev"),
    (7, "__ZNK16IOAESAccelerator12getMetaClassEv"),
    (86, "__ZN16IOAESAccelerator5startEP9IOService"),
    (111, "__ZNK16IOAESAccelerator11getWorkLoopEv"),
    (117, "__ZN16IOAESAccelerator20callPlatformFunctionEPK8OSSymbolbPvS3_S3_S3_"),
    (168, "__ZN16IOAESAccelerator16getAlgorithmNameEv"),
    (169, "__ZN16IOAESAccelerator10performAESEPvS0_P4taskyP7IOAESIV14IOAESOperationP12IOAESKeyDataPFvS0_iES0_"),
    (170, "__ZN16IOAESAccelerator10performAESEP18IOMemoryDescriptorS1_yP7IOAESIV14IOAESOperationP12IOAESKeyDatayyPFvPviES8_"),
    (171, "__ZN16IOAESAccelerator14isKeySupportedEj"),
    (172, "__ZN16IOAESAccelerator19getSupportedOptionsEv"),
    (173, "__ZN16IOAESAccelerator17performAESQuantumEP23IOAESAcceleratorCommand"),
    (174, "__ZN16IOAESAccelerator18completeAESQuantumEP23IOAESAcceleratorCommand"),
    (175, "__ZN16IOAESAccelerator19performImmediateAESEP23IOAESAcceleratorCommand"),
    (176, "__ZN16IOAESAccelerator18disableHardwareKeyEj"),
    (177, "__ZN16IOAESAccelerator17createSpecialKeysEv"),
    (178, "__ZN16IOAESAccelerator12_queueLockedEP23IOAESAcceleratorCommand"),
    (179, "__ZN16IOAESAccelerator13_startCommandEv"),
    (180, "__ZN16IOAESAccelerator12_completeAESEP23IOAESAcceleratorCommand"),
];

/// The assembly of the parent's bindings, from the class reader's record of this kernelcache (`classes`:
/// IOAESAccelerator-24A446-v54.json, kernel/prelink/classes.py's record of the class, a copy of that one class).
pub fn bindings(classes: &Path) -> Result<(String, String)> {
    let script = "build-oneios-aes";
    let record = ClassRecord::load(classes, CLASS, script)?;
    if !record.is_shape("com.apple.iokit.IOCryptoAcceleratorFamily", 0x120, 181)? {
        fail!("{script}: {CLASS} is not the class OriginalAESABI.h describes (0x120 bytes, 181 slots, IOCryptoAcceleratorFamily)");
    }
    let family = record.own_slots()?;
    if !family.iter().copied().eq(SLOTS.iter().map(|(slot, _)| *slot)) {
        fail!("{script}: {CLASS} overrides or adds slots {}, not {}: the method order must be reviewed", pylist(&family),
              pylist(SLOTS.iter().map(|(slot, _)| slot)));
    }
    record.check_structors(script, CLASS)?;
    let mut functions = vec![("__ZN16IOAESAcceleratorC2EPK11OSMetaClass".to_string(), record.constructor(script, CLASS)?),
                             ("__ZN16IOAESAcceleratorD2Ev".to_string(), record.base_destructor()?)];
    for (slot, name) in SLOTS {
        functions.push((name.to_string(), record.slot(slot)?));
    }
    Ok(record.bindings("build-oneios-aes.py", "__ZN16IOAESAccelerator10gMetaClassE", "_oneios_aes", &functions))
}

/// NativeAES.cpp with the software hardware keys (`keys`: SoftwareAESKeys.inc's text), as Droid-VM's
/// build-droidvm-devices.py stages it.
pub fn staged_text(text: String, keys: &str) -> Result<String> {
    let include = format!("#include <kern/task.h>\n{keys}");
    gen::replace_once(text, &[
        ("#include <kern/task.h>\n", &include),
        ("  bool isKeySupported(unsigned selector) override { return selector == 0; }\n",
         "  bool isKeySupported(unsigned selector) override { return selector == 0 || droidvmHardwareKey(selector); }\n"),
        ("  if (key->selector || (operation != IOAESEncrypt && operation != IOAESDecrypt)) {\n",
         "  IOAESKeyData droidvmKey;\n  key = droidvmKeyFor(key, droidvmKey);\n  if (key->selector || (operation != IOAESEncrypt && operation != IOAESDecrypt)) {\n"),
    ], |anchor| format!("build-oneios-aes: NativeAES.cpp no longer has exactly one {}", anchor.trim()))
}

fn staged_native_aes(software_aes: &Path, keys: &Path, out: &Path) -> Result<PathBuf> {
    let staged = out.join("NativeAES.cpp"); // the same file name: the static initializer is named after it
    gen::write_text(&staged, &staged_text(gen::read_text(&software_aes.join("NativeAES.cpp"))?, &gen::read_text(keys)?)?)?;
    Ok(staged)
}

pub fn main() -> Result<()> {
    let ctx = Ctx::new("build-oneios-aes", "run through the kernel build")?;
    let here = ctx.repo.join("kernel/patches/oneios-hosted/aes");
    let software_aes = ctx.repo.join("external/Droid-VM-UniXNU/drivers/SoftwareAES");
    let keys = ctx.repo.join("external/UniXNU-droidvm/package/SoftwareAESKeys.inc");
    let classes = here.join("IOAESAccelerator-24A446-v54.json");
    gen::need_files(&[ctx.repo.join("drivers/build.py"), software_aes.join("NativeAES.cpp"), software_aes.join("OriginalAESABI.h"), keys.clone(),
                      ctx.records.join("iokit/DEVELOPMENT/IOPlatformExpert.cpo.json"), here.join("OneiOSSoftwareAES.cpp")],
                    |path| format!("build-oneios-aes: {} missing (external/Droid-VM-UniXNU: git submodule update --init drivers/SoftwareAES; \
                                    scripts/setup/get-references.sh UniXNU-droidvm)", path.display()))?;
    if !classes.is_file() {
        fail!("build-oneios-aes: {} missing: kernel/prelink/classes.py makes it from the kernelcache", classes.display());
    }
    let out = ctx.tree.join("build/oneios-aes");
    gen::mkdirs(&out)?;
    let record = ctx.record("iokit")?;
    let compile = Compile { ctx: &ctx, shown: 6000 };
    let include = ["-I".to_string(), gen::s(&software_aes)];
    let mut objects = Vec::new();
    for source in [here.join("OneiOSSoftwareAES.cpp"), staged_native_aes(&software_aes, &keys, &out)?] {
        objects.push(compile.object(&record, &source, &out.join(gen::stem(&source) + ".o"), &include)?);
    }
    // NativeAES's static initializer registers its class: it must run inside the board's module load, not with the
    // kernel's own initializers. Out of __mod_init_func, and global so OneiOSSoftwareAES.cpp can call it.
    let late = out.join("NativeAES.late.o");
    gen::late_object(&gen::which("llvm-objcopy", "objcopy"), &out.join("NativeAES.o"), &late, &["__DATA,__mod_init_func"],
                     "__GLOBAL__sub_I_NativeAES.cpp")?;
    objects[1] = late;
    let (stubs, targets) = bindings(&classes)?;
    objects.extend(gen::assemble(&record, &out, &[("IOAESAccelerator-bindings", &stubs), ("IOAESAccelerator-originals", &targets)])?);
    let archive = out.join("liboneiosaes.a");
    gen::archive(&archive, &objects)?;
    gen::require_definitions(&ctx, &archive, &REQUIRED)?;
    gen::write_objects(&ctx, &out, Some("iokit"), &[here.join("OneiOSSoftwareAES.cpp"), software_aes.join("NativeAES.cpp"),
                                                    software_aes.join("OriginalAESABI.h"), keys, classes])?;
    println!("build-oneios-aes: {} ({} objects, {CLASS} bound at its 24A446 iPhone18,2 addresses)", archive.display(), objects.len());
    Ok(())
}
