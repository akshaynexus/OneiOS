/* ---- GLI: CA calls disp[slot](rctx, gl arguments...) on the table -getMacroContextPrivate gives ---- */
#define NGL_SLOTS 1036
#define NGL_GL_TEXTURE_RECTANGLE 0x84F5
#define NGL_UNITS 16
#define NGL_FBFETCH_UNIT 15
#define NGL_NAMES 8192                  /* texture / program / shader / renderbuffer names tracked in tables */

struct ngl_surf;                        /* surface.c: one IOSurface copied into a resource of ours */

struct ngl_rect_prog { GLuint program; GLint scale, sampler; };

/* per GL context: shadows of state that Apple's GL has and Mesa's GLES has not */
struct ngl_state {
	GLuint unit_2d[NGL_UNITS], unit_rect[NGL_UNITS], unit_held[NGL_UNITS];
	uint16_t tex_w[NGL_NAMES], tex_h[NGL_NAMES];
	uint8_t tex_argb[NGL_NAMES];
	uint8_t tex_rect[NGL_NAMES];              /* 1: first bound as a rectangle texture, its defaults set */
	struct ngl_surf *tex_surf[NGL_NAMES];    /* copy mode: the surface a texture name shows */
	struct ngl_surf *rb_surf[NGL_NAMES];     /* copy mode: the surface a renderbuffer name stores */
	uint8_t shader_kind[NGL_NAMES];          /* bit 0: rect sampler, bit 1: emulated fbfetch */
	char rect_sampler[NGL_NAMES][24];        /* (only for shaders with bit 0) */
	struct ngl_rect_prog rect_prog[NGL_NAMES]; /* by program name; .program == 0: none */
	GLint fbf_sampler[NGL_NAMES], fbf_scale[NGL_NAMES];   /* location + 1, 0: none */
	uint16_t prog_units[NGL_NAMES];          /* bit u: a sampler reads unit u; bit 15: known */
	GLuint program;                          /* glUseProgram's (hand slot) */
	const GLfloat *matrix;                   /* the last glUniformMatrix4fv value (CA's own place: Jesvi-iOS) */
	GLuint plain, plain_matrix_loc, plain_textured_loc;   /* the program of the draws CA makes with none */
	unsigned writes;                         /* copy mode: draws into copied surfaces since the last flush */
};

struct ngl_gli {
	void *rctx;                     /* = this; CA reads {rctx, disp[]} */
	void *disp[NGL_SLOTS];
	unsigned api;
	struct ngl_ctx *ctx;
	struct ngl_state *st;
	void *shared;                   /* gld shared-state pointer = the EAGLSharegroup, NULL if none */
	struct ngl_gli *share_next;     /* plugin context list (gli_context.c, under its share_lock) */
	int binds;                      /* threads that have this context as ngl_cur */
	bool zombie;                    /* destroyed while current on another thread: freed later */
	void *view;                     /* the attached CAEAGLLayer native window, NULL if none */
	IOSurfaceRef view_surface;      /* its current IOSurface, retained; released on unbind/destroy */
	unsigned view_colorformat;
	GLuint view_rb;                 /* the renderbuffer that has the drawable as storage */
	void *view_cb[4];               /* EAGLNativeWindowCallbacksRec we gave the window (view.c) */
	int32_t pending[9];             /* the last gliSetInteger 0x38e (an 0x399 with invert binds it again) */
	bool has_pending;
};

