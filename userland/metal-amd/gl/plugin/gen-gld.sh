# OneiOSRadeonGL.bundle: the GLD exports libGFXShared looks up. The POSIX sh + awk port of iOSPlus10 NegroniGL's
# plugin/gen-gld.py (Python is not used in this tree: CLAUDE.md), with the same output.
#
#   gen-gld.sh gld-names.txt gld.c OUT_stubs.c OUT_exports.txt
#
# libGFXShared (gfxInitializeLibrary) dlsym()s gldInitializeLibrary, gldGetVersion and the 129 names of
# _gfx_gld_names (gld-names.txt, table order); one missing name drops the plug-in. gld.c defines the ones the bundle
# needs (a line that starts with the name and "("). Every other name becomes a stub that logs once and returns
# kCGLBadState (0x2717). The exports list is the 129 names, gldInitializeLibrary and gldTerminateLibrary, the 18 GLI
# names eagl_init binds (gli_table.c), gliTerminateLibrary (eagl_dealloc calls it unchecked) and oneios_gl_probe
# (the lasting probe, gl_core.c), each with Mach-O's leading underscore.
set -eu
[ $# -eq 4 ] || { echo "usage: gen-gld.sh gld-names.txt gld.c OUT_stubs.c OUT_exports.txt" >&2; exit 2; }
names=$1 gld=$2 out_c=$3 out_exports=$4
GLI="gliChoosePixelFormat gliDestroyPixelFormat gliQueryRendererInfo gliDestroyRendererInfo gliCreateContext
gliCreateContextWithShared gliDestroyContext gliAttachDrawable gliAttachDrawableWithOptions gliSetInteger gliGetInteger
gliGetAttribute gliSetAttribute gliCopyAttributes gliGetMemoryAnnotationList gliGetVersion gliBindViewES
gliPresentViewES"
EXTRA_GLD="gldInitializeLibrary gldTerminateLibrary"
EXTRA="gliTerminateLibrary oneios_gl_probe"

defined=$(sed -n 's/^\(gld[A-Za-z0-9_]*\)[ \t]*(.*/\1/p' "$gld" | sort -u)
awk -v defined="$defined" -v extra_gld="$EXTRA_GLD" -v gli="$GLI" -v extra="$EXTRA" -v out_c="$out_c" \
    -v out_exports="$out_exports" '
BEGIN { nd = split(defined, d, "\n"); for (i = 1; i <= nd; i++) if (d[i] != "") def[d[i]] = 1 }
/^#/ || NF == 0 { next }
{ if ($1 in seen) dup++; seen[$1] = 1; name[n++] = $1 }
END {
  if (n != 129 || dup) { printf "gen-gld: expected 129 distinct names, found %d (%d repeated)\n", n, dup > "/dev/stderr"; exit 1 }
  split(extra_gld, eg, " "); for (i in eg) xg[eg[i]] = 1
  for (k in def) if (!(k in seen) && !(k in xg)) { printf "gen-gld: gld.c defines %s, which libGFXShared does not use\n", k > "/dev/stderr"; exit 1 }
  for (k in xg) if (!(k in def)) { printf "gen-gld: gld.c must define %s\n", k > "/dev/stderr"; exit 1 }
  ng = split(gli, g, /[ \n]+/)
  if (ng != 18) { printf "gen-gld: expected 18 GLI names, found %d\n", ng > "/dev/stderr"; exit 1 }
  print "/* generated by userland/metal-amd/gl/plugin/gen-gld.sh from gld-names.txt: do not edit */" > out_c
  print "#include \"gld.h\"\n" > out_c
  stubs = 0; in_gld = 0
  for (i = 0; i < n; i++) {
    if (name[i] in def) { in_gld++; continue }
    printf "NGL_GLD int %s(void);\n", name[i] > out_c
    printf "NGL_GLD int %s(void) { return ngl_gld_unexpected(%d, \"%s\"); }\n", name[i], i, name[i] > out_c
    stubs++
  }
  printf "" > out_exports
  for (i = 0; i < n; i++) printf "_%s\n", name[i] > out_exports
  split(extra_gld, a, " "); for (i = 1; i in a; i++) printf "_%s\n", a[i] > out_exports
  for (i = 1; i <= ng; i++) printf "_%s\n", g[i] > out_exports
  split(extra, a, " "); for (i = 1; i in a; i++) printf "_%s\n", a[i] > out_exports
  printf "gen-gld: %d GLD names, %d in gld.c, %d stubs, %d GLI names + gliTerminateLibrary + oneios_gl_probe\n", n, in_gld, stubs, ng > "/dev/stderr"
}' "$names"
